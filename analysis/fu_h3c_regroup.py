"""H3c with folds grouped by canonical problem versus the original grouping by item (second review, item G;
DEVIATIONS D18). Exploratory. Compares the per-layer out-of-fold AUROCs of the original run
(results/fu/4B/fu-h3c-test-4B-aac4cc6) with the regrouped run (results/v2/fu/4B/fu-h3c-regroup-test-4B-*): mean over
layers above the embedding layer, maximum, and the largest per-layer difference; the layer-0 invariant of both.
-> reports/fu_08_h3c_regroup.md, analysis/out/fu_08_h3c_regroup.json
Usage: python analysis/fu_h3c_regroup.py
"""
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
ORIG = ROOT / "results" / "fu" / "4B" / "fu-h3c-test-4B-aac4cc6"


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    new = sorted((ROOT / "results" / "v2" / "fu" / "4B").glob("fu-h3c-regroup-test-4B-*"))[-1]
    a = json.loads((ORIG / "metrics.json").read_text(encoding="utf-8"))
    b = json.loads((new / "metrics.json").read_text(encoding="utf-8"))
    out = {"original run": ORIG.name, "regrouped run": new.name, "n items": b["n_items"], "n canonical": b["n_canonical"],
           "layer0 invariant": {"original": a["layer0_invariant"], "regrouped": b["layer0_invariant"]}, "by target": {}}
    for pos in ("mean", "last"):
        for t in ("role", "label"):
            x, y = np.array(a["auroc"][pos][t]), np.array(b["auroc"][pos][t])
            out["by target"][f"{t} @ {pos}"] = {"mean over layers 1+": [float(x[1:].mean()), float(y[1:].mean())],
                                                "max": [float(x.max()), float(y.max())],
                                                "largest per-layer |difference|": float(np.abs(x - y).max())}
    (ROOT / "analysis" / "out" / "fu_08_h3c_regroup.json").write_text(json.dumps(out, indent=1), encoding="utf-8", newline="\n")
    L = ["# H3c: folds grouped by canonical problem vs by item (generated by analysis/fu_h3c_regroup.py)", "",
         f"**Exploratory** (DEVIATIONS D18). {out['n items']} D-inj test items in {out['n canonical']} canonical problems. "
         f"Layer-0 invariant: original {out['layer0 invariant']['original']}, regrouped {out['layer0 invariant']['regrouped']}.", "",
         "| Target @ position | Mean over layers 1+ (item → canonical) | Max (item → canonical) | Largest per-layer difference |",
         "|---|---|---|---|"]
    for k, v in out["by target"].items():
        L.append(f"| {k} | {v['mean over layers 1+'][0]:.4f} → {v['mean over layers 1+'][1]:.4f} | {v['max'][0]:.4f} → {v['max'][1]:.4f} | "
                 f"{v['largest per-layer |difference|']:.4f} |")
    (ROOT / "reports" / "fu_08_h3c_regroup.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
