"""Power simulation (design §7.4) from the dev pilots' paired outcome patterns (analysis/out/p2_pairs_<model>.json).

For a paired binary contrast the joint outcome of an item is one of (1,1), (1,0), (0,1), (0,0). The pilot gives the
discordance D = p10 + p01 and the concordant split. A scenario sets the discordance (pilot x {0.5, 1, 1.5}) and the
true risk difference (p10 - p01); items are drawn from that multinomial and the pre-registered test is applied.
Power is computed at the conservative Holm level alpha / family_size (the first Holm step) and at alpha.

Scenarios: equivalence / non-inferiority: effect in {0, delta/2, delta}; superiority: {delta/2, delta,
0.5 x pilot estimate}. n is the test-split size. Never planned on the tuned pilot effect alone.
Usage: python analysis/power.py
"""
import json
from pathlib import Path

import numpy as np

from stats import one_sided_paired, tost

ROOT = Path(__file__).resolve().parents[1]
DELTA, ALPHA, SIMS, SEED = 0.03, 0.05, 2000, 0


def pattern_probs(disc, effect, concordant_right_share):
    p10, p01 = (disc + effect) / 2, (disc - effect) / 2
    if p01 < 0 or p10 < 0:
        return None
    rest = 1 - disc
    return np.array([rest * concordant_right_share, p10, p01, rest * (1 - concordant_right_share)])


def simulate(test, n, probs, sims=SIMS, seed=SEED):
    """Rejection rate of `test(x, y) -> p` at levels returned as a dict of p arrays."""
    rng = np.random.default_rng(seed)
    pats = np.array([[1, 1], [1, 0], [0, 1], [0, 0]])
    ps = np.empty(sims)
    for s in range(sims):
        k = rng.choice(4, size=n, p=probs)
        xy = pats[k]
        ps[s] = test(xy[:, 0], xy[:, 1])
    return ps


def pilot_stats(pairs):
    x = np.array([it["outcomes"][0] for it in pairs["items"]], int)
    y = np.array([it["outcomes"][1] for it in pairs["items"]], int)
    p10, p01 = ((x == 1) & (y == 0)).mean(), ((x == 0) & (y == 1)).mean()
    conc = (x == y)
    share = ((x == 1) & conc).sum() / max(1, conc.sum())
    return {"n_pilot": len(x), "disc": p10 + p01, "effect": p10 - p01, "concordant_right_share": share}


def power_table(name, pairs, n, kind, family_size):
    st = pilot_stats(pairs)
    rows = []
    effects = ({"equivalence": (0.0, DELTA / 2, DELTA), "superiority": (DELTA / 2, DELTA, 0.5 * abs(st["effect"]))}[kind])
    for dmult in (0.5, 1.0, 1.5):
        disc = max(st["disc"] * dmult, 1e-3)
        for eff in effects:
            probs = pattern_probs(disc, eff, st["concordant_right_share"])
            if probs is None:
                rows.append({"disc": disc, "effect": eff, "power_holm": None, "power_alpha": None})
                continue
            test = (lambda x, y: tost(x, y, DELTA)) if kind == "equivalence" else \
                   (lambda x, y: min(1.0, 2 * min(one_sided_paired(x, y, 0, "greater"), one_sided_paired(x, y, 0, "less"))))
            ps = simulate(test, n, probs)
            rows.append({"disc": disc, "effect": eff, "power_holm": float((ps < ALPHA / family_size).mean()),
                         "power_alpha": float((ps < ALPHA).mean())})
    return {"name": name, "kind": kind, "n": n, "pilot": st, "rows": rows}


def main():
    out = {}
    for model in ("4B", "1.7B"):
        f = ROOT / "analysis" / "out" / f"p2_pairs_{model}.json"
        if not f.exists():
            out[model] = "TODO(missing: pilot pairs)"
            continue
        pairs = json.loads(f.read_text())
        res = []
        # D-nat test n = 1,455; D-inj test n = 1,635 (data/processed); family size 6 (Tier 1) as the conservative step.
        if pairs["H1a_F2_vs_F1"]["items"]:
            res.append(power_table("H1a TOST F2 vs F1", pairs["H1a_F2_vs_F1"], 1455, "equivalence", 6))
        h1d = pairs["H1d_F5_vs_perm"]
        if h1d["items"]:
            two = {"items": [{"outcomes": [it["outcomes"][0], it["outcomes"][1]]} for it in h1d["items"]]}
            res.append(power_table("H1d F5 vs F3-perm[0]", two, 1455, "superiority", 6))
        for key, label in (("H3a_dinj_F0", "H3a-role (D-inj, F0)"),):
            cells = pairs[key]
            if cells["items"]:
                # role contrast as a paired comparison of the user vs assistant cells within the self label
                two = {"items": [{"outcomes": [it["outcomes"][2], it["outcomes"][0]]} for it in cells["items"]]}
                res.append(power_table(label + " user/self vs assistant/self", two, 1635, "superiority", 6))
        out[model] = res
    dest = ROOT / "analysis" / "out" / "power.json"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(json.dumps(out, indent=1))
    pc = lambda x: "—" if x is None else f"{100 * x:.1f}"
    lines = ["# Power simulation (generated by analysis/power.py; dev pilots, design §7.4)", "",
             f"δ = {100 * DELTA:.0f} pp, α = {ALPHA}, {SIMS} simulations; power at the first Holm step (α/6) and at α. "
             "Scenario discordance = pilot × {0.5, 1, 1.5}; 'infeasible' = the effect exceeds the discordance. "
             "H1d and H2a are re-examined in 02_selfverdict_tables.md and 02_power_h2a_tables.md.", ""]
    for model, res in out.items():
        lines += [f"## Qwen3-{model}", ""]
        if isinstance(res, str):
            lines += [res, ""]
            continue
        lines += ["| Hypothesis | Test n | Pilot discordance % | Pilot effect (pp) | Scenario discordance % | Effect (pp) | "
                  "Power α/6 | Power α |", "|---|---|---|---|---|---|---|---|"]
        for h in res:
            for r in h["rows"]:
                lines.append(f"| {h['name']} ({h['kind']}) | {h['n']} | {pc(h['pilot']['disc'])} | {pc(h['pilot']['effect'])} | "
                             f"{pc(r['disc'])} | {pc(r['effect'])} | "
                             + (" infeasible | infeasible |" if r["power_holm"] is None else f" {r['power_holm']:.2f} | {r['power_alpha']:.2f} |"))
        lines.append("")
    (ROOT / "reports" / "02_power_tables.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps(out, indent=1)[:4000])


if __name__ == "__main__":
    main()
