"""Per-block estimates during P4 (prereg §8: estimates and CIs only; no p-value, Holm or outcome category before P6).
-> reports/04_<out>.md and analysis/out/<out>.json.

Runs the frozen analysis (analysis/p6_confirmatory.py `analyse`, main labels) on whatever blocks of a test spec are
synced, and keeps only n, estimate and 95 % cluster-bootstrap CI per hypothesis and secondary estimand. p-values are
computed inside `analyse` and dropped here unread. Adds, per synced run: rows by status (ok / unparsed / truncated / ...)
and the calls the scorer guard stopped (DEVIATIONS D1).
Usage: python analysis/p4_block_estimates.py --spec configs/p4_spec_4B_test.json --out p4_4B_tier1 [--n-boot 10000]
"""
import argparse
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "analysis"))
from p6_confirmatory import N_BOOT, analyse, jl  # noqa: E402

ORDER = ["H1a", "H1b", "H1d", "H2a", "H2b(i) F2 - F0", "H2b(ii) F3(1.0) - F0", "H3a-role", "H3a-label", "H3b"]
KEEP = ("n", "est", "lo", "hi", "kind", "margin", "context", "auroc_probe", "auroc_verbal", "status_note")


def pp(x, scale=100):
    return "–" if x is None else f"{scale * x:+.1f}"


def run_card(run):
    d = ROOT / run
    rows = jl(d / "rows.jsonl") if (d / "rows.jsonl").exists() else []
    st = Counter(r.get("status") for r in rows if r.get("prompt_key") is not None or r.get("run"))
    m = json.loads((d / "metrics.json").read_text()) if (d / "metrics.json").exists() else {}
    return {"rows": len(rows), "status": dict(st), "scorer_guarded": m.get("scorer_guarded", []),
            "truncated_by_condition": {k: v.get("truncated", 0) for k, v in m.get("rows", {}).items() if v.get("truncated")}}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--spec", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--n-boot", type=int, default=N_BOOT)
    a = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")
    spec = json.loads((ROOT / a.spec).read_text(encoding="utf-8"))
    res = analyse(spec, boot_n=a.n_boot)
    est = {h: {k: v for k, v in res[h].items() if k in KEEP} for h in ORDER if h in res and "est" in res[h]}
    sec = res.get("secondary", {})
    runs = [spec[k] for k in ("exp01_orig", "exp01_ext", "exp01_1b", "exp01_alt") if spec.get(k)]
    if spec.get("exp3_rows"):
        runs.append(str(Path(spec["exp3_rows"]).parent))
    cards = {r: run_card(r) for r in dict.fromkeys(runs)}
    out = {"spec": a.spec, "n_boot": a.n_boot, "estimates": est, "secondary": sec, "notes": res.get("notes", []),
           "exp3_arms": res.get("exp3_arms"), "runs": cards}
    (ROOT / "analysis" / "out" / f"{a.out}.json").write_text(json.dumps(out, indent=1, default=float))

    L = [f"# P4 per-block estimates, {spec['model']} {spec['split']} (generated by analysis/p4_block_estimates.py)", "",
         f"Spec `{a.spec}`. Estimates in pp (H2a: AUROC difference × 100), 95 % cluster-bootstrap CIs ({a.n_boot} "
         "resamples, clusters = canonical IDs). **Estimates and CIs only**: no p-value, Holm adjustment or outcome "
         "category before P6 (prereg §8).", "", "| Quantity | n | Estimate | 95 % CI |", "|---|---|---|---|"]
    for h, r in est.items():
        L.append(f"| {h} | {r['n']} | {pp(r['est'])} | [{pp(r['lo'])}, {pp(r['hi'])}] |")
    if "H1a" in est and est["H1a"].get("context"):
        c = est["H1a"]["context"]
        L += ["", "H1a context (prereg §0): " + ", ".join(f"{k} {100 * v:.1f} %" for k, v in c.items() if v is not None) + "."]
    if "H2a" in est:
        L += ["", f"H2a: AUROC probe {est['H2a']['auroc_probe']:.3f}, verbal {est['H2a']['auroc_verbal']:.3f}."]
    L += ["", "## Secondary estimands", "", "| Hypothesis | Scope | Estimate | 95 % CI |", "|---|---|---|---|"]
    for h, d in sec.items():
        for scope, v in d.items():
            L.append(f"| {h} | {scope} | {pp(v[0])} | [{pp(v[1])}, {pp(v[2])}] |")
    if res.get("exp3_arms"):
        L += ["", "## Exp 3 arms", "", "| Arm | W->R D-inj | R->W D-nat |", "|---|---|---|"]
        rate = lambda x: "–" if x is None else f"{100 * x:.1f} %"
        L += [f"| {k} | {rate(v['W->R D-inj'])} | {rate(v['R->W D-nat'])} |" for k, v in res["exp3_arms"].items()]
    L += ["", "## Runs", ""]
    for r, c in cards.items():
        g = c["scorer_guarded"]
        L.append(f"- `{r}`: {c['rows']} rows; status {c['status']}; scorer guard stopped {len(g)} distinct call(s)"
                 + (": " + "; ".join(f"{x['fn']}({', '.join(map(repr, x['args']))}) {x['reason']}" for x in g[:10]) if g else "")
                 + (f"; truncated rows by condition {c['truncated_by_condition']}" if c["truncated_by_condition"] else ""))
    L += ["", "Notes from the analysis: " + "; ".join(res.get("notes", [])) + "."]
    (ROOT / "reports" / f"04_{a.out}.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
