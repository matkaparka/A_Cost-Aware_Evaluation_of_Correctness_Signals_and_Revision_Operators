"""P3 pre-freeze checks on 4B dev (cloud/p3e_sequence.sh) -> reports/03_checks_tables.md, analysis/out/p3_checks.json.

1. HF vs vLLM greedy agreement (src/gen/hf_agree.py): identical-output rate, per-position agreement, and the logit gap
   between HF's top token and a0's token at the first mismatch (a gap near 0 is a bf16 near-tie).
2. Thinking budget pilot (src/gen/think_pilot.py): truncation share by budget and dataset, and the budget the rule fixed
   in DECISIONS 2026-11-05 selects (the smallest budget with overall truncation <= 5 %, else the largest).
3. Exp 1B alternative wrapper set (runner --label-set alt): parse and truncation rates per condition, against the main
   wording on the same dev items (P2 run). Validity only; correction outcomes are not compared (src/gen/render.py).
Dev split only. Usage: python analysis/p3_checks.py
"""
import json
from collections import defaultdict
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results" / "p2" / "4B"
RUNS = {"hfagree": "p2-hfagree-dev-4B-b7cf0d6", "think": "p2-think-pilot-dev-4B-b7cf0d6",
        "alt": "p2-exp01-dev-alt-4B-b7cf0d6", "main": "p2-exp01-dev-4B-f7e5011"}
TRUNC_MAX = 0.05   # the thinking budget rule (DECISIONS 2026-11-05)
OUT_MD = ROOT / "reports" / "03_checks_tables.md"


def jl(p):
    return [json.loads(l) for l in open(p, encoding="utf-8")]


def pct(x):
    return f"{100 * x:.1f}"


def main():
    out, lines = {}, ["# P3 pre-freeze checks on 4B dev (generated by analysis/p3_checks.py)", "",
                      "Runs: " + ", ".join(f"`{v}`" for v in RUNS.values()) + ". Dev split only.", ""]

    # 1. HF vs vLLM
    rows = jl(R / RUNS["hfagree"] / "rows.jsonl")
    ident = np.array([r["identical"] for r in rows])
    share = np.array([r["match_share"] for r in rows])
    gaps = np.array([r["logit_gap_at_first"] for r in rows if not r["identical"]])
    first = np.array([r["first_mismatch"] / r["a0_len"] for r in rows if not r["identical"]])
    out["hf_vllm"] = {"n": len(rows), "identical": int(ident.sum()), "rate": float(ident.mean()),
                      "position_agreement_median": float(np.median(share)), "position_agreement_min": float(share.min()),
                      "gap_le": {str(t): float((gaps <= t).mean()) for t in (0.0, 0.25, 0.5, 1.0)},
                      "first_mismatch_rel_median": float(np.median(first))}
    h = out["hf_vllm"]
    lines += ["## 1. HF vs vLLM greedy agreement (design §6 Exp 5, §8: ≥ 98 % identical, else report and keep generation-based "
              "comparisons within one backend)", "",
              "| Items | Identical | Identical % | Per-position agreement, median % | minimum % | First mismatch, median position "
              "(share of a0) |", "|---|---|---|---|---|---|",
              f"| {h['n']} | {h['identical']} | {pct(h['rate'])} | {pct(h['position_agreement_median'])} | "
              f"{pct(h['position_agreement_min'])} | {h['first_mismatch_rel_median']:.2f} |", "",
              "Logit gap between HF's top token and a0's token at the first mismatch (items that diverge):", "",
              "| Gap ≤ 0 (tie) | ≤ 0.25 | ≤ 0.5 | ≤ 1 |", "|---|---|---|---|",
              "| " + " | ".join(pct(h["gap_le"][str(t)]) + " %" for t in (0.0, 0.25, 0.5, 1.0)) + " |", ""]

    # 2. Thinking budget
    m = json.loads((R / RUNS["think"] / "metrics.json").read_text())
    tr = m["truncation_share"]
    budgets = sorted(int(b) for b in tr["all"])
    ok = [b for b in budgets if tr["all"][str(b)] <= TRUNC_MAX]
    chosen = ok[0] if ok else budgets[-1]
    out["thinking"] = {"truncation_share": tr, "mean_out_tokens": m["mean_out_tokens"], "chosen_budget": chosen}
    lines += ["## 2. Thinking-mode budget (4B, dev D-nat, one seed; T 0.6, top-p 0.95, top-k 20, min-p 0)", "",
              "| Dataset | Items | Mean output tokens | " + " | ".join(f"Truncated at {b} %" for b in budgets) + " |",
              "|---|---|---|" + "---|" * len(budgets)]
    n_by = defaultdict(int)
    for r in jl(R / RUNS["think"] / "rows.jsonl"):
        n_by[r["dataset"]] += 1
        n_by["all"] += 1
    for ds in sorted(tr, key=lambda k: (k == "all", k)):
        lines.append(f"| {ds} | {n_by[ds]} | {m['mean_out_tokens'][ds]:.0f} | " + " | ".join(pct(tr[ds][str(b)]) for b in budgets) + " |")
    lines += ["", f"Rule (DECISIONS 2026-11-05): the smallest budget with overall truncation ≤ {pct(TRUNC_MAX)} %, else the "
              f"largest. Selected: **{chosen}** tokens.", ""]

    # 3. Alternative wrapper set
    alt = jl(R / RUNS["alt"] / "rows.jsonl")
    ids = {r["item_id"] for r in alt}
    main_rows = [r for r in jl(R / RUNS["main"] / "rows.jsonl") if r["exp"] == "1B" and r["data"] == "dinj" and r["item_id"] in ids]
    stat = {}
    for name, rs in (("alt", alt), ("main", main_rows)):
        by = defaultdict(list)
        for r in rs:
            by[r["cond"]].append(r["status"])
        stat[name] = {c: {"n": len(v), "unparsed": sum(s in ("unparsed", "conflict") for s in v) / len(v),
                          "truncated": sum(s == "truncated" for s in v) / len(v)} for c, v in by.items()}
    out["alt_wrapper"] = stat
    lines += ["## 3. Exp 1B alternative wrapper set: validity (4B, D-inj dev, the first items of the seeded order)", "",
              "Unparsed (incl. conflicting boxes) and truncated shares; main wording on the same items from the P2 run.", "",
              "| Condition | n | Unparsed % alt | Unparsed % main | Truncated % alt | Truncated % main |", "|---|---|---|---|---|---|"]
    for c in sorted(stat["alt"]):
        a, b = stat["alt"][c], stat["main"].get(c)
        lines.append(f"| {c} | {a['n']} | {pct(a['unparsed'])} | {pct(b['unparsed']) if b else '—'} | {pct(a['truncated'])} | "
                     f"{pct(b['truncated']) if b else '—'} |")
    tot = {k: {f: float(np.mean([v[f] for v in stat[k].values()])) for f in ("unparsed", "truncated")} for k in stat}
    out["alt_wrapper_mean"] = tot
    lines += [f"| **mean over conditions** | | {pct(tot['alt']['unparsed'])} | {pct(tot['main']['unparsed'])} | "
              f"{pct(tot['alt']['truncated'])} | {pct(tot['main']['truncated'])} |", ""]
    (ROOT / "analysis" / "out" / "p3_checks.json").write_text(json.dumps(out, indent=1))
    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(OUT_MD.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
