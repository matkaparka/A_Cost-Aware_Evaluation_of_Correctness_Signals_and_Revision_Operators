"""Thinking subset: outputs that stop inside an unclosed think block (POST HOC, exploratory; written 2026-11-06 after
reading the 4B thinking estimates, DEVIATIONS D11). The pre-specified rule (D7) scores them as unparsed = wrong, and
that rule stays primary. This script only describes them: per condition, how many outputs stop (finish_reason "stop")
without "</think>", and how many of those carry a boxed answer inside the think block that the frozen scorer would
accept if the think block were treated as the answer.
-> reports/04_<out>.md and analysis/out/<out>.json
Usage: python analysis/p4_thinking_unclosed.py --runs <thinking run dirs> --out p4_4B_thinking_unclosed
"""
import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "analysis"))
from p6_confirmatory import jl  # noqa: E402
from src.score.scorer import score  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", nargs="+", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")
    gold = {r["item_id"]: r["gold"] for r in jl("data/processed/dnat.jsonl")}
    n, unclosed, boxed, would_correct = (defaultdict(int) for _ in range(4))
    for run in a.runs:
        for g in jl(Path(run) / "generations.jsonl"):
            c = g["cond"]
            n[c] += 1
            t = g["text"]
            if g["finish_reason"] != "stop" or "</think>" in t:
                continue
            unclosed[c] += 1
            s = score(t.replace("<think>", "", 1) + "\n", gold[g["item_id"]], finish_reason="stop")
            boxed[c] += s["status"] == "ok"
            would_correct[c] += bool(s["correct"])
    out = {c: {"outputs": n[c], "stop_unclosed": unclosed[c], "boxed_inside": boxed[c],
               "would_be_correct": would_correct[c]} for c in sorted(n)}
    (ROOT / "analysis" / "out" / f"{a.out}.json").write_text(json.dumps({"runs": a.runs, "conds": out}, indent=1))
    L = ["# Thinking subset: outputs that stop inside an unclosed think block (generated by "
         "analysis/p4_thinking_unclosed.py)", "",
         "**Post hoc, exploratory (DEVIATIONS D11).** The pre-specified rule (D7) scores these outputs as unparsed = "
         "wrong, and the thinking estimates keep that rule. Counts are over generations (items × seeds), unweighted.", "",
         "| Condition | Outputs | Stop, think block unclosed | … with a parsable boxed answer | … which the scorer accepts |",
         "|---|---|---|---|---|"]
    L += [f"| {c} | {v['outputs']} | {v['stop_unclosed']} | {v['boxed_inside']} | {v['would_be_correct']} |"
          for c, v in out.items()]
    (ROOT / "reports" / f"04_{a.out}.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
