"""Completeness of the run outputs on the control host (before deciding whether the cloud instance can be destroyed).

For every results/**/manifest.json, every file the manifest lists is classed as:
- here: present in the run directory with the manifest's sha256;
- worktree: missing here but present, with the right sha256, in .worktrees/lore-qa (copied here with --copy);
- remote only: listed in the run's remote_only.json (kept only on the cloud instance);
- missing / hash mismatch: anything else.
Also reports, for files present here, whether git tracks them or ignores them (an ignored file is not on GitHub).
Usage: python analysis/p8_completeness.py [--copy]
"""
import argparse
import hashlib
import json
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WT = ROOT / ".worktrees" / "lore-qa"


def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def listed(m):
    """{name: sha256} from a manifest, whatever its layout."""
    for key in ("files", "outputs", "sha256"):
        if isinstance(m.get(key), dict):
            return {k: (v if isinstance(v, str) else v.get("sha256")) for k, v in m[key].items()}
    out = {}
    for k, v in m.items():
        if isinstance(v, dict) and all(isinstance(x, str) and len(x) == 64 for x in v.values()):
            out.update(v)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--copy", action="store_true")
    a = ap.parse_args()
    tracked = set(subprocess.run(["git", "-C", str(ROOT), "ls-files", "results"], capture_output=True, text=True).stdout.split("\n"))
    counts, problems, ignored, copied = {}, [], [], []
    for mf in sorted((ROOT / "results").rglob("manifest.json")):
        d = mf.parent
        m = json.loads(mf.read_text(encoding="utf-8"))
        files = listed(m)
        ro = {e["name"] for e in json.loads((d / "remote_only.json").read_text(encoding="utf-8"))} if (d / "remote_only.json").exists() else set()
        for name, h in files.items():
            p = d / name
            rel = str(p.relative_to(ROOT)).replace("\\", "/")
            if p.exists():
                cls = "here" if (h is None or sha(p) == h) else "hash mismatch"
                if cls == "here" and rel not in tracked:
                    ignored.append((rel, p.stat().st_size))
            elif name in ro:
                cls = "remote only"
            else:
                w = WT / p.relative_to(ROOT)
                if w.exists() and (h is None or sha(w) == h):
                    cls = "worktree"
                    if a.copy:
                        shutil.copy2(w, p)
                        copied.append(rel)
                        ignored.append((rel, p.stat().st_size))
                else:
                    cls = "missing"
            counts[cls] = counts.get(cls, 0) + 1
            if cls in ("missing", "hash mismatch"):
                problems.append((cls, rel))
    L = ["# Completeness of run outputs on the control host (generated by analysis/p8_completeness.py)", "",
         f"Files listed in the run manifests: {sum(counts.values())}; by class: "
         + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())) + ".", "",
         f"Missing or hash mismatch: {len(problems)}."]
    L += [f"- {c}: `{r}`" for c, r in problems]
    if copied:
        L += ["", "Copied from the merged `lore-qa` worktree (hash checked): " + ", ".join(f"`{c}`" for c in copied) + "."]
    L += ["", "Present here but ignored by git (not in the repository; see the release assets in `reports/09_artifacts.md`):", "",
          "| File | MB |", "|---|---|"] + [f"| `{r}` | {s / 1e6:.1f} |" for r, s in sorted(ignored, key=lambda x: -x[1])]
    (ROOT / "reports" / "09_completeness.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
