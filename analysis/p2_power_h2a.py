"""H2a power (design §7.4; H2a: test AUROC of the dev-trained frozen probe > that of the verbal P(yes)_norm, for
initial-answer correctness). results/p1 + results/p2 -> reports/02_power_h2a_tables.md, analysis/out/power_h2a.json.

Inputs, dev only: out-of-fold probe scores at the selected layer and C (the same grouped 5-fold CV as
src/probe/train.py) and the verbal score s = log P(yes) - log P(no). Test right/wrong counts per model come from the
P1 initial answers (allowed before the freeze, design §5.3).
Simulation: draw a test set of the test right/wrong counts from the dev items (with replacement, within label);
one-sided paired DeLong test of AUROC(probe) > AUROC(verbal) at the first Holm step alpha / 6. DeLong stands in for
the pre-registered paired item bootstrap, which is too slow inside a simulation. Scenarios: the dev effect (the
OOF probe is trained on 80% of dev, while the selection over the layer x C grid makes the effect optimistic), half of
it (Gaussian noise added to the standardized probe score, its scale set on dev so that the expected probe AUROC is
the verbal AUROC plus half the dev gap; noise cannot create an ensemble gain), and test pools 1.5x and 2x larger.
Usage: python analysis/p2_power_h2a.py
"""
import json
import math
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "reports" / "02_power_h2a_tables.md"
ALPHA, FAMILY, SIMS, SEED = 0.05, 6, 2000, 0
# The runs behind the selected probes (DECISIONS 2026-11-04); a superseded P1 run sits next to the current one.
RUNS = {"4B": {"initial": "p1-initial-4B-d2ebdea", "verbal": "p1-verbal-4B-d2ebdea", "acts": "p2-acts-dev-4B-f7e5011",
               "probe": "p2-probe-dev-4B-4eb1a4b"},
        "1.7B": {"initial": "p1-initial-1.7B-d2ebdea", "verbal": "p1-verbal-1.7B-d2ebdea", "acts": "p2-acts-dev-1.7B-f7e5011",
                 "probe": "p2-probe-dev-1.7B-4eb1a4b"}}


def jl(p):
    return [json.loads(l) for l in open(p, encoding="utf-8")]


def oof_scores(X, y, groups, C, folds=5, seed=0):
    from sklearn.linear_model import LogisticRegression
    from sklearn.model_selection import StratifiedGroupKFold
    from sklearn.pipeline import make_pipeline
    from sklearn.preprocessing import StandardScaler
    s = np.zeros(len(y))
    for tr, te in StratifiedGroupKFold(folds, shuffle=True, random_state=seed).split(X, y, groups):
        clf = make_pipeline(StandardScaler(), LogisticRegression(C=C, max_iter=2000)).fit(X[tr], y[tr])
        s[te] = clf.decision_function(X[te])
    return s


def delong_paired(a, b, y):
    """One-sided p for AUROC(a) > AUROC(b) on the same items (DeLong et al. 1988 structural components)."""
    pos, neg = y == 1, y == 0
    def comps(s):
        sp, sn = s[pos], s[neg]
        cmp = (sp[:, None] > sn[None, :]) + 0.5 * (sp[:, None] == sn[None, :])
        return cmp.mean(1), cmp.mean(0), cmp.mean()
    va, wa, auc_a = comps(a)
    vb, wb, auc_b = comps(b)
    m, n = pos.sum(), neg.sum()
    sv, sw = np.cov(np.vstack([va, vb])), np.cov(np.vstack([wa, wb]))
    var = (sv[0, 0] + sv[1, 1] - 2 * sv[0, 1]) / m + (sw[0, 0] + sw[1, 1] - 2 * sw[0, 1]) / n
    z = (auc_a - auc_b) / math.sqrt(max(var, 1e-12))
    return 0.5 * math.erfc(z / math.sqrt(2)), auc_a, auc_b


def noise_for_auc(p, y, target, rng, draws=20):
    """Scale of N(0, sigma^2) noise on the standardized score p giving expected AUROC = target (bisection on dev)."""
    from sklearn.metrics import roc_auc_score
    z = (p - p.mean()) / p.std()
    lo, hi = 0.0, 10.0
    for _ in range(30):
        mid = (lo + hi) / 2
        auc = np.mean([roc_auc_score(y, z + mid * rng.standard_normal(len(z))) for _ in range(draws)])
        lo, hi = (mid, hi) if auc > target else (lo, mid)
    return z, (lo + hi) / 2


def main():
    out, lines = {}, ["# H2a power (generated by analysis/p2_power_h2a.py; dev split only, test right/wrong counts)", "",
                      f"One-sided paired DeLong test of AUROC(probe) > AUROC(verbal) at α/{FAMILY} (first Holm step), "
                      f"{SIMS} simulated test sets drawn from dev within label. The dev effect is optimistic (layer and "
                      "C were selected on the same items). 'Half effect': Gaussian noise on the probe score, scaled on dev so "
                      "the expected probe AUROC is the verbal AUROC plus half the dev gap. Pool ×k: k times the test "
                      "right and wrong counts.", "",
                      "| Model | Dev AUROC probe (OOF) | Dev AUROC verbal | Test right / wrong | Scenario | Power |",
                      "|---|---|---|---|---|---|"]
    rng = np.random.default_rng(SEED)
    for model in ("4B", "1.7B"):
        R1, R2 = ROOT / "results" / "p1" / model, ROOT / "results" / "p2" / model
        acts = R2 / RUNS[model]["acts"] / "acts.npz"
        probe = R2 / RUNS[model]["probe"] / "probe_selection.json"
        sel = json.loads(probe.read_text())["selected"]
        z = np.load(acts)
        ids, y = z["ids"], z["correct0"].astype(int)
        dnat = {r["item_id"]: r for r in jl(ROOT / "data" / "processed" / "dnat.jsonl")}
        groups = np.array([dnat[i]["canonical_id"] for i in ids])
        p = oof_scores(z["X"][:, sel["layer"]].astype(np.float32), y, groups, sel["C"])
        verbal = {r["item_id"]: r for r in jl(R1 / RUNS[model]["verbal"] / "verbal.jsonl")}
        v = np.array([math.log(max(verbal[i]["p_yes"], 1e-300)) - math.log(max(verbal[i]["p_no"], 1e-300)) for i in ids])
        _, auc_p, auc_v = delong_paired(p, v, y)
        init = jl(R1 / RUNS[model]["initial"] / "initial.jsonl")
        n_right = sum(r["split"] == "test" and r["correct"] for r in init)
        n_wrong = sum(r["split"] == "test" and not r["correct"] for r in init)
        res = {"dev_auroc_probe_oof": auc_p, "dev_auroc_verbal": auc_v, "test_right": n_right, "test_wrong": n_wrong,
               "probe": {"layer": sel["layer"], "C": sel["C"]}, "scenarios": {}}
        zp, sigma = noise_for_auc(p, y, auc_v + (auc_p - auc_v) / 2, rng)
        res["half_effect_noise_sigma"] = sigma
        for name, half, k in (("dev effect", False, 1.0), ("half effect", True, 1.0), ("dev effect, pool ×1.5", False, 1.5),
                              ("dev effect, pool ×2", False, 2.0), ("half effect, pool ×2", True, 2.0)):
            pos_i, neg_i = np.where(y == 1)[0], np.where(y == 0)[0]
            hits = 0
            for _ in range(SIMS):
                idx = np.concatenate([rng.choice(pos_i, int(round(k * n_right))), rng.choice(neg_i, int(round(k * n_wrong)))])
                scores = zp[idx] + sigma * rng.standard_normal(len(idx)) if half else p[idx]
                pv, _, _ = delong_paired(scores, v[idx], y[idx])
                hits += pv < ALPHA / FAMILY
            res["scenarios"][name] = hits / SIMS
            lines.append(f"| {model} | {auc_p:.3f} | {auc_v:.3f} | {n_right} / {n_wrong} | {name} | {hits / SIMS:.2f} |")
        out[model] = res
    (ROOT / "analysis" / "out" / "power_h2a.json").write_text(json.dumps(out, indent=1))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(OUT.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
