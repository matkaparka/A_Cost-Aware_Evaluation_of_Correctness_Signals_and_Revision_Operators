"""Cloud cost and GPU-hours by line item, for the P8 autonomy log (CLAUDE.md §5 P8; rule 1: numbers by script).

Source: cloud/ledger.jsonl (one row per closed session; compute_usd and its source per row) and the storage accrual
rule of cloud/session.py (provisioned GB x USD/GB-month x months since the instance was created). Line items are
session ranges, with boundaries fixed here:
- P0-P3 (setup, benchmarks, data, dev pilots, prereg): sessions that started before the prereg freeze commit
  (08657ca, 2026-11-05T04:06:49+08:00 = 2026-11-04T20:06:49Z);
- P4-P5 (main runs, 8B, Exp 4, streams): later sessions up to session 27;
- follow-ups after the first draft (lore, Group 1, Tulu-3-8B, Group 2; D14-D16): sessions 28-32;
- second review (Tulu readout check, H3c regroup, MMLU-Pro validation; D18): sessions 33-34;
- third review (D19): no cloud session (analyses of stored outputs on the laptop).
The ledger's figures are the agent's records (jl get costs and hours x price); they are not JarvisLabs billing, which
only Liam can provide for reconciliation.
Usage: python analysis/p8_costs.py -> reports/08_costs.md, analysis/out/08_costs.json
"""
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "cloud"))
import session as S  # noqa: E402

FREEZE = datetime(2026, 11, 4, 20, 6, 49, tzinfo=timezone.utc)


def ts(s):
    s = s.replace("Z", "+00:00")
    if len(s) == 22:   # "2026-11-03T07:09+00:00" without seconds
        s = s[:16] + ":00" + s[16:]
    return datetime.fromisoformat(s)


def item(r):
    n = r["session"]
    if n >= 35:
        return "archive before the instance decision (no GPU work)"
    if n >= 33:
        return "second review (D18)"
    if n >= 28:
        return "follow-ups after the first draft (D14-D16)"
    return "P0-P3 (before the freeze)" if ts(r["billing_start"]) < FREEZE else "P4-P5 main runs"


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    rows = [json.loads(l) for l in open(ROOT / "cloud" / "ledger.jsonl", encoding="utf-8") if l.strip()]
    order = ["P0-P3 (before the freeze)", "P4-P5 main runs", "follow-ups after the first draft (D14-D16)", "second review (D18)",
             "archive before the instance decision (no GPU work)"]
    agg = {k: {"sessions": [], "hours": 0.0, "compute_usd": 0.0} for k in order}
    for r in rows:
        a = agg[item(r)]
        a["sessions"].append(r["session"])
        a["hours"] += r["hours"]
        a["compute_usd"] += r["compute_usd"]
    compute, storage = S.spent(rows)
    # After the instance was destroyed (cloud/destroyed.json), storage stops accruing at the confirmed time.
    dj = ROOT / "cloud" / "destroyed.json"
    end_note = "to now"
    if dj.exists():
        d = json.loads(dj.read_text(encoding="utf-8"))
        end = datetime.fromisoformat(d["confirmed_absent_at"].replace("Z", "+00:00"))
        storage = S.STORAGE_GB * S.STORAGE_USD_PER_GB_MONTH * (end - S.CREATED).total_seconds() / (30 * 86400)
        end_note = f"until the instance was destroyed (confirmed absent {d['confirmed_absent_at']}; final)"
    out = {"line items": agg, "compute total": sum(a["compute_usd"] for a in agg.values()),
           "hours total": sum(a["hours"] for a in agg.values()), "storage accrued": storage, "storage accrued period": end_note,
           "ledger compute (session.py)": compute, "cap": S.CAP_USD, "reserve": S.RESERVE_USD,
           "storage reserve": S.STORAGE_RESERVE_USD, "computed at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%MZ")}
    (ROOT / "analysis" / "out" / "08_costs.json").write_text(json.dumps(out, indent=1), encoding="utf-8", newline="\n")
    L = ["# Cloud cost and GPU-hours by line item (generated by analysis/p8_costs.py)", "",
         f"Source: `cloud/ledger.jsonl` ({len(rows)} closed sessions) and the storage rule of `cloud/session.py`, computed "
         f"{out['computed at']}. These are the agent's ledger figures; Liam checked them against the provider's billing "
         "on 2026-11-08 and found no discrepancy.", "",
         "| Line item | Sessions | GPU-hours | Compute USD |", "|---|---|---|---|"]
    for k in order:
        a = agg[k]
        s = a["sessions"]
        L.append(f"| {k} | {min(s)}–{max(s)} ({len(s)}) | {a['hours']:.1f} | {a['compute_usd']:.2f} |")
    L += [f"| third review (D19) | none | 0.0 | 0.00 |",
          f"| **Total compute** | {len(rows)} | {out['hours total']:.1f} | {out['compute total']:.2f} |", "",
          f"Storage accrued {end_note} (100 GB, provisioned, also while paused): {storage:.2f} USD. "
          f"Compute + storage: {out['compute total'] + storage:.2f} USD, against a cap of {S.CAP_USD} USD "
          f"(fixed reserve {S.RESERVE_USD:.2f}, storage reserve {S.STORAGE_RESERVE_USD:.2f}).", "",
          "Other costs: none recorded by the agent (no paid APIs; the laptop's electricity and the subscription that runs "
          "the agent are not in the ledger).", ""]
    (ROOT / "reports" / "08_costs.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
