"""Minimum complete sample per block (design §10; prereg §10) -> reports/03_min_n_tables.md, analysis/out/min_n.json,
and a check that configs/blocks.yaml carries these values.

Blocks run by src/exp/runner.py (Exp 0, 1A, 1B, the alternative-wrapper subset) and the Exp 2 activation block are
atomic: the runner generates all items of a pool in one engine call, so a stopped block has no complete chunk and is
re-run in full at its locked commit (cheap: priority 2 costs about $7). Their min_n is their planned n.
Chunked blocks: min_n is the smallest n at which the block's confirmatory test keeps central-scenario power >= 0.8 at
the first Holm step (alpha / 6), by the normal approximation n = ((z_{1-a} + z_{0.8}) * sd / effect)^2, with sd the
dev standard deviation of the item-level difference under the central scenario; for blocks without a confirmatory
test, half the planned n.
- 4B-exp3 (H3b, one-sided, effect delta): sd from the P2 Exp 3 dev pilot (main setting minus the mean of the 5 random
  arms on D-inj items), rescaled to the central scenario's discordance (pilot x 1) by keeping the pilot sd.
Usage: python analysis/p3_min_n.py
"""
import json
import math
from pathlib import Path

import numpy as np
import yaml
from scipy.stats import norm

ROOT = Path(__file__).resolve().parents[1]
ALPHA, FAMILY, POWER, DELTA = 0.05, 6, 0.8, 0.03
EXP3 = ROOT / "results" / "p2" / "4B" / "p2-steer-pilot-4B-7ea8f7d" / "confirm_rows.jsonl"


def n_for(sd, effect, one_sided=True):
    za = norm.ppf(1 - ALPHA / FAMILY / (1 if one_sided else 2))
    return int(math.ceil(((za + norm.ppf(POWER)) * sd / effect) ** 2))


def main():
    cfg = yaml.safe_load((ROOT / "configs" / "blocks.yaml").read_text(encoding="utf-8"))
    planned = {"4B-exp0": 160, "4B-exp1a": 1455, "4B-exp1a-ext": 3597, "4B-exp1b": 3090, "4B-exp1b-alt": 300,
               "4B-exp2": 5052, "4B-exp3": 1547, "4B-exp5-item": 400, "8B-exp1a": 1455, "8B-exp1b": 3090,
               "1.7B-tier1": 3090, "4B-thinking": 300, "8B-exp1a-ext": 3597, "1.7B-exp1a-ext": 3597, "8B-exp2": 1455,
               "4B-exp1c-robust": 300, "4B-exp4": 200, "4B-streams": 1, "8B-thinking": 300}
    atomic = {"4B-exp0", "4B-exp1a", "4B-exp1a-ext", "4B-exp1b", "4B-exp1b-alt", "4B-exp2", "8B-exp1a", "8B-exp1b",
              "1.7B-tier1", "8B-exp1a-ext", "1.7B-exp1a-ext", "8B-exp2"}
    rows = [json.loads(l) for l in open(EXP3, encoding="utf-8")]
    arms = {}
    for r in rows:
        if r["data"] == "dinj":
            arms.setdefault(r["item_id"], {})[r["run"]] = int(bool(r["correct"]))
    rnd = [f"top2:random{k}" for k in range(5)]
    d = np.array([v["top2:role"] - np.mean([v[x] for x in rnd]) for v in arms.values() if all(x in v for x in ["top2:role"] + rnd)])
    sd3 = float(d.std(ddof=1))
    out, lines = {}, ["# Minimum complete sample per block (generated by analysis/p3_min_n.py)", "",
                      f"Atomic blocks (one runner call per pool): min_n = planned n. H3b: dev sd of d_i {sd3:.3f} on {len(d)} "
                      f"D-inj items; one-sided at α/{FAMILY}, power {POWER}, effect δ = {100 * DELTA:.0f} pp. Others: half the "
                      "planned n.", "", "| Block | Planned n | Rule | min_n | blocks.yaml |", "|---|---|---|---|---|"]
    yml = {b["id"]: b for b in cfg["blocks"]}
    ok = True
    for bid, n in planned.items():
        if bid in atomic:
            m, rule = n, "atomic"
        elif bid == "4B-exp3":
            m, rule = min(n, n_for(sd3, DELTA)), "H3b power"
        else:
            m, rule = max(1, n // 2), "half"
        have = yml.get(bid, {}).get("min_n")
        ok &= have == m
        out[bid] = {"planned": n, "rule": rule, "min_n": m, "blocks_yaml": have}
        lines.append(f"| {bid} | {n} | {rule} | {m} | {have}{'' if have == m else ' (MISMATCH)'} |")
    lines += ["", f"configs/blocks.yaml {'matches' if ok else 'DOES NOT match'} these values."]
    (ROOT / "analysis" / "out" / "min_n.json").write_text(json.dumps(out, indent=1))
    (ROOT / "reports" / "03_min_n_tables.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
