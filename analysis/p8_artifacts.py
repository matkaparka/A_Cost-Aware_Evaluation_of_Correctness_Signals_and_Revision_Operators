"""Inventory of the reproducible material (third review §6.1; P8): what is on the control host, what stays only on the
run host, and how each remote-only file can be rebuilt. Reads results/**/manifest.json and results/**/remote_only.json.
Usage: python analysis/p8_artifacts.py -> reports/09_artifacts.md
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def human(n):
    for u in ("B", "KB", "MB", "GB"):
        if n < 1024 or u == "GB":
            return f"{n:.0f} {u}" if u == "B" else f"{n:.1f} {u}"
        n /= 1024


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    res = ROOT / "results"
    runs = sorted({p.parent for p in res.rglob("manifest.json")})
    by_exp = defaultdict(lambda: [0, 0])
    for r in runs:
        exp = r.relative_to(res).parts[0]
        by_exp[exp][0] += 1
        by_exp[exp][1] += sum(f.stat().st_size for f in r.rglob("*") if f.is_file())
    remote = []
    for p in sorted(res.rglob("remote_only.json")):
        for e in json.loads(p.read_text(encoding="utf-8")):
            remote.append((str(p.parent.relative_to(ROOT)).replace("\\", "/"), e["name"], e["bytes"], e.get("sha256_ok")))
    L = ["# Reproducible material: inventory (generated by analysis/p8_artifacts.py)", "",
         "Every number and table in the paper is produced by a script in `analysis/` from files in `results/` (CLAUDE.md rule 1). "
         "The frozen protocols are `prereg.md` (hash in STATUS.md), `docs/planning/lore_qa/prereg_addendum.md` and "
         "`docs/planning/validation_v2/addendum.md`; every later change is in `DEVIATIONS.md` (D1–D19) and `DECISIONS.md`. "
         "Each run directory holds its config, a version manifest with sha256 hashes (checked at sync) and its outputs; "
         "`runs.jsonl` lists every run with its locked code commit.", "",
         "## Runs on the control host (this repository)", "",
         "| Experiment directory | Runs | Size on disk |", "|---|---|---|"]
    L += [f"| results/{e}/ | {n} | {human(b)} |" for e, (n, b) in sorted(by_exp.items())]
    L += ["", "## Files kept only on the run host", "",
          "Files over about 100 MB stayed on the paused instance (`/home/results/...`) because the sync link was slow; each is "
          "listed with its sha256 in the run's `remote_only.json` and `manifest.json`. They are rebuildable from the run's "
          "config and locked commit (activations by re-running the extraction stage; generations by re-running the same "
          "greedy stage under `VLLM_BATCH_INVARIANT=1`, which reproduced frozen rows exactly where checked). They are all "
          "activation files: inputs to stages whose outputs (probe selections and scores, H3c decoding AUROCs) are synced. "
          "Every analysis script that produces a paper number runs from files on the control host, except the H3c decoding "
          "runs (the H3c part of the Group 1 follow-ups and its canonical regrouping, `fu_08`), which ran on the run host "
          "next to the activations; their result files are synced.", "",
          "| Run directory | File | Size | sha256 checked on the run host |", "|---|---|---|---|"]
    L += [f"| {d} | {n} | {human(b)} | {'yes' if ok else 'not recorded'} |" for d, n, b, ok in remote]
    dj = ROOT / "cloud" / "destroyed.json"
    fate = (f"They were deleted with the instance (confirmed absent {json.loads(dj.read_text(encoding='utf-8'))['confirmed_absent_at']}; "
            "`cloud/destroyed.json`), after Liam's decision; the instance's other intermediate files are summarized in "
            "`reports/09_completeness.md`." if dj.exists() else
            "They are lost if the instance is destroyed; whether to fetch any before that is Liam's decision (CLAUDE.md §6).")
    L += ["", f"Remote-only total: {human(sum(b for _, _, b, _ in remote))} in {len(remote)} files. {fate}", ""]
    ra = ROOT / "analysis" / "out" / "09_release_assets.json"
    if ra.exists():
        assets = json.loads(ra.read_text(encoding="utf-8"))
        L += ["## Large local files attached to the GitHub release (not in git)", "",
              "These files are on the control host but too large for git or excluded by `.gitignore`. They are attached as "
              "assets of the release `artifacts-v1` of the private repository (matkaparka/probing_freezing_models). Each "
              "asset name is the file's path below `results/` with `/` replaced by `__`. Check each sha256 against the run's "
              "`manifest.json` after download.", "",
              "| Asset | Source path | Size | sha256 |", "|---|---|---|---|"]
        L += [f"| {a['asset']} | {a['source']} | {human(a['bytes'])} | `{a['sha256'][:16]}…` |" for a in assets]
        L += [""]
    L += ["Completeness check against every run manifest: `reports/09_completeness.md` (`analysis/p8_completeness.py`).", ""]
    (ROOT / "reports" / "09_artifacts.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(L[-12:]))


if __name__ == "__main__":
    main()
