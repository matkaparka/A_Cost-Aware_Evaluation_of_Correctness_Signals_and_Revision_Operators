"""Data card of the D-nat expansion (CLAUDE.md P1.3 rules: dev full statistics; test item counts, right/wrong counts
and unparsed rates only) -> reports/03_data_ext_tables.md.
Inputs: data/processed/ext (src/data/expand.py) and the P3 initial-answer runs of 1.7B, 4B and 8B.
Usage: python analysis/p3_data_card_ext.py
"""
import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXT = ROOT / "data" / "processed" / "ext"
RUNS = {m: f"p1-initial-ext-{m}-45575c2" for m in ("1.7B", "4B", "8B")}


def jl(p):
    return [json.loads(l) for l in open(p, encoding="utf-8")]


def main():
    man = json.loads((EXT / "build_ext_manifest.json").read_text())
    st = man["stats"]
    items = jl(EXT / "dnat_ext.jsonl")
    dropped = jl(EXT / "dropped_ext.jsonl")
    lines = ["# D-nat expansion data card (generated by analysis/p3_data_card_ext.py)", "",
             f"Source `{man['source']['repo']}@{man['source']['revision']}`, split {man['source']['split']}, "
             f"{man['source']['rows']} rows. Kept {st['kept_items']} items ({st['canonical_ids']} canonical IDs, {st['merges']} "
             f"merges of near-duplicates within the expansion); dropped {len(dropped)} already in the pool "
             f"(dev {st['dropped_in_pool_by_split']['dev']}, test {st['dropped_in_pool_by_split']['test']}; by match: "
             + ", ".join(f"{k} {v}" for k, v in sorted(Counter(d['how'] for d in dropped).items())) + "; matched source: "
             + ", ".join(f"{k} {v}" for k, v in sorted(Counter(d['matched'][0] for d in dropped).items())) + "). "
             f"Gold = last `\\boxed{{}}` of the solution; agreement with MATH-500's answer field "
             f"{st['gold_agreement_with_math500']:.3f} on {st['gold_check_n']} overlapping problems.", ""]
    split = Counter(r["split"] for r in items)
    lines += ["## Items by split, level and subject", "",
              "| Level | Dev | Test |", "|---|---|---|"]
    lv = Counter((r["level"], r["split"]) for r in items)
    for level in sorted({r["level"] for r in items}):
        lines.append(f"| {level} | {lv[(level, 'dev')]} | {lv[(level, 'test')]} |")
    lines += [f"| **all** | {split['dev']} | {split['test']} |", "", "| Subject | Dev | Test |", "|---|---|---|"]
    sj = Counter((r["subject"], r["split"]) for r in items)
    for s in sorted({r["subject"] for r in items}):
        lines.append(f"| {s} | {sj[(s, 'dev')]} | {sj[(s, 'test')]} |")
    meta = {r["item_id"]: r for r in items}
    lines += ["", "## Initial answers a0 (greedy, non-thinking, 4096-token budget)", "",
              "Dev: full statistics. Test: right / wrong counts and the unparsed + truncated rate only.", "",
              "| Model | Dev n | Dev acc % | Dev truncated % | Dev unparsed % | Dev mean a0 tokens | Test right / wrong | "
              "Test truncated or unparsed % |", "|---|---|---|---|---|---|---|---|"]
    for m, run in RUNS.items():
        rows = jl(ROOT / "results" / "p1" / m / run / "initial.jsonl")
        dev = [r for r in rows if r["split"] == "dev"]
        test = [r for r in rows if r["split"] == "test"]
        pct = lambda k, n: f"{100 * k / n:.1f}"
        lines.append(f"| {m} | {len(dev)} | {pct(sum(r['correct'] for r in dev), len(dev))} | "
                     f"{pct(sum(r['status'] == 'truncated' for r in dev), len(dev))} | "
                     f"{pct(sum(r['status'] not in ('ok', 'truncated') for r in dev), len(dev))} | "
                     f"{sum(len(r['a0_token_ids']) for r in dev) / len(dev):.0f} | "
                     f"{sum(r['correct'] for r in test)} / {sum(not r['correct'] for r in test)} | "
                     f"{pct(sum(r['status'] != 'ok' for r in test), len(test))} |")
    lines += ["", "Dev accuracy by level (4B):", "", "| Level | n | Acc % |", "|---|---|---|"]
    acc = defaultdict(list)
    for r in jl(ROOT / "results" / "p1" / "4B" / RUNS["4B"] / "initial.jsonl"):
        if r["split"] == "dev":
            acc[meta[r["item_id"]]["level"]].append(r["correct"])
    for level in sorted(acc):
        lines.append(f"| {level} | {len(acc[level])} | {100 * sum(acc[level]) / len(acc[level]):.1f} |")
    lines += ["", "Caveat: the expansion is the part of the MATH test set outside MATH-500. Some public training recipes "
              "have trained on that part, so its contamination risk may differ from MATH-500's (prereg §0)."]
    (ROOT / "reports" / "03_data_ext_tables.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
