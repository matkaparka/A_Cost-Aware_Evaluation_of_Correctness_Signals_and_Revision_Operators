"""P0: measured rates from results/p0/**/metrics.json -> reports/00_compute_rates.md (CLAUDE.md rule 1).
Usage: python analysis/p0_compute.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "reports" / "00_compute_rates.md"


def load():
    runs = {}
    for p in sorted((ROOT / "results" / "p0").glob("*/*/metrics.json")):
        man = json.loads((p.parent / "manifest.json").read_text())
        runs[p.parent.name] = {"metrics": json.loads(p.read_text()), "manifest": man}
    return runs


def f(x, nd=1):
    return "—" if x is None else (f"{x:.{nd}f}" if isinstance(x, float) else str(x))


def main():
    runs = load()
    lines = ["# P0 measured rates (generated by analysis/p0_compute.py; do not edit by hand)", ""]
    lines += ["Source runs: " + ", ".join(f"`{k}` ({v['manifest']['gpu']}, commit {v['manifest']['code_commit'][:7]})"
                                        for k, v in runs.items()), ""]

    lines += ["## vLLM generation (greedy, non-thinking unless noted; GSM8K-train fixtures)", "",
              "| Run | Block | n | Mean out tok | Max out tok | Output tok/s | Total tok/s | GPU-s per gen | Load s |",
              "|---|---|---|---|---|---|---|---|---|"]
    for k, v in runs.items():
        m = v["metrics"]
        for blk in ("round1", "round2", "thinking", "lora_roundrobin", "lora_zero"):
            if blk in m:
                b = m[blk]
                lines.append(f"| {k} | {blk} | {b['n']} | {f(b['mean_output_tokens'])} | {b['max_output_tokens']} | "
                             f"{f(b['output_tok_per_s'], 0)} | {f(b['total_tok_per_s'], 0)} | {f(b['wall_s'] / b['n'], 3)} | "
                             f"{f(m.get('load_s'), 0)} |")
    lines += ["", "## Vertical slice outcomes (fixtures only; minimal scorer)", "",
              "| Run | acc0 | acc1 | W→R | R→W | unparsed0 | truncated0 | thinking acc | thinking truncated | zero-adapter = base |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    for k, v in runs.items():
        m = v["metrics"]
        if "acc0" in m or "zero_adapter_identical_greedy" in m:
            th = m.get("thinking", {})
            lines.append(f"| {k} | {f(m.get('acc0'), 3)} | {f(m.get('acc1'), 3)} | {f(m.get('w2r'))} | {f(m.get('r2w'))} | "
                         f"{f(m.get('unparsed0'), 3)} | {f(m.get('truncated0'))} | {f(th.get('acc'), 3)} | "
                         f"{f(th.get('truncated'))} | {f(m.get('zero_adapter_identical_greedy'), 3)} |")
    lines += ["", "## Greedy determinism in vLLM (4B, 128 fixtures, 512 tokens, LoRA-enabled engine)", "",
              "| VLLM_BATCH_INVARIANT | Repeat call identical | Other batch identical | Batch size 1 identical (16) | "
              "Zero adapter = base | Base wall s |", "|---|---|---|---|---|---|"]
    for k, v in runs.items():
        m = v["metrics"]
        if "repeat_identical" in m:
            lines.append(f"| {m['VLLM_BATCH_INVARIANT']} | {f(m['repeat_identical'], 3)} | {f(m['other_batch_identical'], 3)} | "
                         f"{f(m['batch1_identical_first16'], 3)} | {f(m['zero_adapter_identical'], 3)} | {f(m['base_wall_s'], 2)} |")
    lines += ["", "## HF backend", "",
              "| Run | Teacher-forced tok/s | Activations s/item | Bytes/position (all layers) | HF batched gen tok/s | "
              "Patching s/pair | TTT s/update | TTT reset exact | Norm rel. err | HF=vLLM greedy | Peak VRAM GB |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
    for k, v in runs.items():
        m = v["metrics"]
        if "teacher_forced" not in m:
            continue
        ttt, ag = m.get("ttt", {}), m.get("hf_vllm_agreement", {})
        lines.append(f"| {k} | {f(m['teacher_forced']['tok_per_s'], 0)} | {f(m['activations']['s_per_item'], 3)} | "
                     f"{m['activations']['bytes_per_position_all_layers']} | {f(m.get('hf_generate_batched', {}).get('output_tok_per_s'), 0)} | "
                     f"{f(m.get('patching', {}).get('s_per_pair_fwd_bwd'), 3)} | {f(ttt.get('s_per_update_mean'), 2)} | "
                     f"{f(ttt.get('reset_logits_equal'))} | {f(ttt.get('realized_norm_max_rel_err'), 6)} | "
                     f"{f(ag.get('identical'))}/{f(ag.get('n'))} | {f(m.get('peak_vram_gb'), 1)} |")
    lines += stop_path()
    lines += block_costs(runs)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(OUT.read_text(encoding="utf-8"))


def stop_path():
    """Stop-path test outcomes (CLAUDE.md §6) from results/p0/stop_path/*.log."""
    import re
    out = ["", "## Stop-path test (CLAUDE.md §6)", "",
           "Seconds from arming to a confirmed `Paused` in `jl get` (polled every 20 s). The run-host watchdog fires "
           "about 60 s after arming, by design.", "",
           "| Scenario | Path tested | Result | Seconds |", "|---|---|---|---|"]
    paths = {"normal": "run host", "job_crash": "run host", "sync_hang": "run host (flush times out at 300 s)",
             "control_offline": "run host alone (control watchdog stopped)", "control_path": "control host (STOP flag)"}
    for scen in paths:
        p = ROOT / "results" / "p0" / "stop_path" / f"stop_path_{scen}.log"
        m = re.search(rf"RESULT {scen}: (paused after (\d+) s|NOT paused.*)", p.read_text(encoding="utf-8")) if p.exists() else None
        res = "not run" if not p.exists() else ("paused" if m and m.group(2) else "FAILED")
        out.append(f"| {scen} | {paths[scen]} | {res} | {m.group(2) if m and m.group(2) else '—'} |")
    return out


def rates_by_model(runs):
    """GPU-seconds per work unit (configs/blocks.yaml), per model, from the P0 runs."""
    r = {}
    for v in runs.values():
        m, key = v["metrics"], v["metrics"]["model"]
        x = r.setdefault(key, {})
        if "round2" in m:
            x["gen"] = m["round2"]["wall_s"] / m["round2"]["n"]
            x["mean_out"] = m["round1"]["mean_output_tokens"]
            x["vllm_load"] = m["load_s"]
        if "thinking" in m:
            x["think"] = m["thinking"]["wall_s"] / m["thinking"]["n"]
        if "lora_roundrobin" in m:
            x["lora_gen"] = m["lora_roundrobin"]["wall_s"] / m["lora_roundrobin"]["n"]
        if "teacher_forced" in m:
            tf = m["teacher_forced"]
            x["fwd"] = (tf["tokens"] / tf["n"]) / tf["tok_per_s"]
            x["hf_load"] = m["load_s"]
        if "hf_generate_batched" in m:
            x["hf_tok_s"] = m["hf_generate_batched"]["output_tok_per_s"]
        if "patching" in m:
            x["fwdbwd"] = m["patching"]["s_per_pair_fwd_bwd"]
        if "ttt" in m:
            x["ttt"] = m["ttt"]["s_per_update_mean"]
        if "hf_vllm_agreement" in m:
            a = m["hf_vllm_agreement"]
            x["hf_gen_b1"] = a["wall_s"] / a["n"]
    for x in r.values():
        if "hf_tok_s" in x and "mean_out" in x:
            x["hf_gen"] = x["mean_out"] / x["hf_tok_s"]
    # All study generation runs with VLLM_BATCH_INVARIANT=1 (the only mode that passed the determinism
    # check); the benchmarks above ran without it, so vLLM units are scaled by the measured 4B slowdown.
    det = {v["metrics"]["VLLM_BATCH_INVARIANT"]: v["metrics"] for v in runs.values()
           if "VLLM_BATCH_INVARIANT" in v["metrics"]}
    bi_factor = det["1"]["base_wall_s"] / det["0"]["base_wall_s"] if {"0", "1"} <= set(det) else None
    if bi_factor:
        for x in r.values():
            for unit in ("gen", "think", "lora_gen"):
                if unit in x:
                    x[unit] *= bi_factor
    r["_bi_factor"] = bi_factor
    # Units not measured on a model are scaled from 4B by that model's measured gen-time ratio (marked).
    scaled = {}
    base = r.get("4B", {})
    for key, x in r.items():
        if key.startswith("_"):
            continue
        for unit in ("think", "lora_gen", "fwd", "fwdbwd", "ttt", "hf_gen", "hf_gen_b1"):
            if unit not in x and unit in base and "gen" in x and "gen" in base:
                x[unit] = base[unit] * x["gen"] / base["gen"]
                scaled.setdefault(key, []).append(unit)
        if "ttt" in x and "hf_gen_b1" in x:
            x["stream"] = x["ttt"] + x["hf_gen_b1"]
    return r, scaled


def block_costs(runs):
    import yaml
    cfg = yaml.safe_load((ROOT / "configs" / "blocks.yaml").read_text(encoding="utf-8"))
    d = cfg["defaults"]
    rates, scaled = rates_by_model(runs)
    bi = rates.pop("_bi_factor")
    out = ["", f"## Block cost estimate (measured rates × configs/blocks.yaml volumes × {d['overhead']} overhead; "
                f"${d['price_per_h']:.2f}/h)", "",
           (f"vLLM generation units are multiplied by {bi:.2f}, the measured 4B slowdown of VLLM_BATCH_INVARIANT=1, "
            "which all study generation uses." if bi else "No batch-invariance factor available."),
           "Units not measured on a model are scaled from 4B by the measured generation-time ratio: "
           + ("; ".join(f"{k}: {', '.join(v)}" for k, v in scaled.items()) or "none") + ".",
           "Thinking-mode rates come from a 64-sequence batch, an upper bound on cost.", "",
           "| Priority | Block | Model | GPU-h | USD | Cumulative USD | Missing rates |", "|---|---|---|---|---|---|---|"]
    cum = 0.0
    for b in sorted(cfg["blocks"], key=lambda b: b["priority"]):
        models = list(rates) if b["model"] == "all" else [b["model"]]
        sec, missing = 0.0, []
        for mk in models:
            x = rates.get(mk, {})
            for unit, n in (b.get("units") or {}).items():
                if unit in x:
                    sec += n * x[unit]
                else:
                    missing.append(f"{mk}:{unit}")
            if b.get("units"):
                sec += d["load_s"]["vllm"] + d["load_s"]["hf"]
        h = sec * d["overhead"] / 3600
        usd = h * d["price_per_h"]
        cum += usd
        out.append(f"| {b['priority']} | {b['id']} | {b['model']} | {h:.2f} | {usd:.2f} | {cum:.2f} | {', '.join(missing) or '—'} |")
    out += ["", f"Total over all blocks: ${cum:.2f} of GPU time. Not included: idle time while code is written "
                "with the instance running, storage, and the P0 session itself (see cloud/ledger.jsonl)."]
    return out


if __name__ == "__main__":
    main()
