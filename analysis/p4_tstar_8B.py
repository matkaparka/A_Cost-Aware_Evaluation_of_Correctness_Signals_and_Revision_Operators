"""8B self-verdict threshold t* by the prereg §11 adaptation rule, step 1 (no judgment: the 4B rule on 8B dev).
-> analysis/out/selfverdict_8B.json and reports/04_tstar_8B.md.

The rule of analysis/p2_selfverdict.py: s = log P(yes) - log P(no) on the original-pool dev items; t* = the midpoint
between adjacent sorted scores that maximizes balanced accuracy (ties: the lowest). The same code path is first run on
4B and 1.7B and must reproduce their frozen t* (analysis/out/selfverdict.json) exactly. The P2 script's H1d power part
needs a dev runner run, which 8B does not have and the rule does not need.
Usage: python analysis/p4_tstar_8B.py
"""
import json
import math
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "analysis"))
from p2_selfverdict import balanced_acc, jl, score  # noqa: E402


def t_star(model):
    init = {r["item_id"]: r for r in jl(ROOT / "results" / "p1" / model / f"p1-initial-{model}-d2ebdea" / "initial.jsonl")}
    verbal = [r for r in jl(ROOT / "results" / "p1" / model / f"p1-verbal-{model}-d2ebdea" / "verbal.jsonl")
              if r["split"] == "dev"]
    scored = [(score(r), init[r["item_id"]]["correct"]) for r in verbal if score(r) is not None]
    s = np.array([x for x, _ in scored])
    y = np.array([c for _, c in scored], bool)
    u = np.unique(s)
    cands = (u[:-1] + u[1:]) / 2
    ba = np.array([balanced_acc(s, y, t) for t in cands])
    t = float(cands[int(np.argmax(ba))])
    return {"model": model, "n_dev": len(verbal), "n_unscored": len(verbal) - len(scored), "t_star_s": t,
            "t_star_p_yes_norm": 1 / (1 + math.exp(-t)), "balanced_acc_t_star": float(ba.max()),
            "balanced_acc_half": float(balanced_acc(s, y, 0.0))}


def main():
    frozen = json.loads((ROOT / "analysis" / "out" / "selfverdict.json").read_text())
    for m in ("4B", "1.7B"):
        r = t_star(m)
        assert r["t_star_s"] == frozen[m]["t_star_s"], (m, r["t_star_s"], frozen[m]["t_star_s"])
    r = t_star("8B")
    (ROOT / "analysis" / "out" / "selfverdict_8B.json").write_text(json.dumps({"8B": r}, indent=1))
    lines = ["# 8B self-verdict threshold (generated by analysis/p4_tstar_8B.py)", "",
             "Prereg §11 step 1: the 4B rule applied to 8B dev, by script. The same code reproduces the frozen 4B and "
             "1.7B thresholds exactly.", "",
             f"- dev items {r['n_dev']} (unscored {r['n_unscored']}); t* = {r['t_star_s']!r} "
             f"(P(yes)_norm ≥ {r['t_star_p_yes_norm']!r}); dev balanced accuracy {r['balanced_acc_t_star']:.4f} "
             f"vs {r['balanced_acc_half']:.4f} at 0.5."]
    (ROOT / "reports" / "04_tstar_8B.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
