"""Scorer 1.1.1 vs the frozen 1.1.0 (DEVIATIONS 2026-11-05): same verdict on every stored output?
-> reports/04_scorer_guard_check.md and analysis/out/scorer_guard_check.json.

1.1.0 is loaded from the freeze commit's blob. Both score every stored text with its own gold and finish reason:
  - P1 initial answers a0 of 1.7B, 4B and 8B, original pool and expansion, dev and test (pre-feedback quantities);
  - every Exp 1A / 1B / Tsui generation of the dev runner runs (Exp 0 has no scorer call; the Tsui cell uses the
    last-number rule);
  - the Exp 3 dev pilot's confirmation texts.
Compared: status, extracted answer and correct. Only agreement counts are reported. Run on the laptop the guard is
inactive, so this checks the 1.1.1 refactor (string equality first, cache, set-gold parse); a guarded call on the run
host is listed in that run's metrics.json ("scorer_guarded").
Usage: python analysis/p4_scorer_guard_check.py
"""
import importlib.util
import json
import subprocess
import sys
import time
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.score import scorer as new  # noqa: E402

FREEZE = "08657caf44035d3772bb68ba6d38c823b664e304"
P1 = {m: [f"p1-initial-{m}-d2ebdea", f"p1-initial-ext-{m}-45575c2"] for m in ("1.7B", "4B", "8B")}
EXP01 = {"4B": ["p2-exp01-dev-4B-f7e5011", "p2-exp01-dev-ext-4B-6cd867e", "p2-exp01-dev-tstar-4B-6cd867e",
                "p2-exp01-dev-alt-4B-b7cf0d6"],
         "1.7B": ["p2-exp01-dev-1.7B-f7e5011", "p2-exp01-dev-ext-1.7B-6cd867e", "p2-exp01-dev-tstar-1.7B-6cd867e"]}
STEER = "p2-steer-pilot-4B-7ea8f7d"
OUT_MD = ROOT / "reports" / "04_scorer_guard_check.md"
OUT_JSON = ROOT / "analysis" / "out" / "scorer_guard_check.json"


def jl(p):
    return [json.loads(l) for l in open(p, encoding="utf-8")]


def frozen_scorer():
    src = subprocess.run(["git", "show", f"{FREEZE}:src/score/scorer.py"], capture_output=True, text=True,
                         encoding="utf-8", cwd=ROOT, check=True).stdout
    path = ROOT / "analysis" / "out" / "_scorer_1_1_0.py"
    path.write_text(src, encoding="utf-8")
    spec = importlib.util.spec_from_file_location("scorer_1_1_0", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    path.unlink()
    assert mod.SCORER_VERSION == "1.1.0"
    return mod


def main():
    old = frozen_scorer()
    data = {}
    for f in ("dnat.jsonl", "ext/dnat_ext.jsonl", "dinj.jsonl"):
        for r in jl(ROOT / "data" / "processed" / f):
            data[r["item_id"]] = r
    jobs = []   # (source, split, text, gold, finish_reason, last_number)
    for m, runs in P1.items():
        for run in runs:
            for r in jl(ROOT / "results" / "p1" / m / run / "initial.jsonl"):
                jobs.append((f"a0 {m}", r["split"], r["a0"], data[r["item_id"]]["gold"], r["finish_reason"], False))
    for m, runs in EXP01.items():
        for run in runs:
            d = ROOT / "results" / "p2" / m / run
            gen = {g["prompt_key"]: g for g in jl(d / "generations.jsonl")}
            seen = set()
            for r in jl(d / "rows.jsonl"):
                if r["exp"] == "0" or r.get("prompt_key") is None or r["prompt_key"] in seen:
                    continue
                seen.add(r["prompt_key"])
                g = gen[r["prompt_key"]]
                jobs.append((f"exp01 {m}", "dev", g["text"], data[r["item_id"]]["gold"], g["finish_reason"],
                             r["exp"] == "tsui"))
    for r in jl(ROOT / "results" / "p2" / "4B" / STEER / "confirm_texts.jsonl"):
        jobs.append(("steer 4B", "dev", r["text"], data[r["item_id"]]["gold"], r.get("finish_reason"), False))

    counts, diffs, t = Counter(), [], {"old": 0.0, "new": 0.0}
    for src, split, text, gold, fr, ln in jobs:
        t0 = time.time()
        a = old.score(text, gold, finish_reason=fr, last_number=ln)
        t1 = time.time()
        b = new.score(text, gold, finish_reason=fr, last_number=ln)
        t["old"] += t1 - t0
        t["new"] += time.time() - t1
        key = f"{src} | {split}"
        counts[key] += 1
        if a != b:
            diffs.append({"source": key, "old": a, "new": b})
    out = {"n": len(jobs), "by_source": dict(sorted(counts.items())), "differences": len(diffs),
           "diff_rows": diffs[:50], "seconds": {k: round(v, 1) for k, v in t.items()},
           "guarded_inline": new.GUARDED, "frozen_commit": FREEZE, "scorer_version": new.SCORER_VERSION}
    OUT_JSON.write_text(json.dumps(out, indent=1))
    lines = ["# Scorer 1.1.1 vs frozen 1.1.0 (generated by analysis/p4_scorer_guard_check.py)", "",
             f"Stored outputs scored by both: {len(jobs)}; differing verdicts (status, answer or correct): "
             f"**{len(diffs)}**. Scoring time on the laptop: 1.1.0 {t['old']:.0f} s, 1.1.1 {t['new']:.0f} s.", "",
             "| Source | Split | n |", "|---|---|---|"]
    lines += [f"| {k.split(' | ')[0]} | {k.split(' | ')[1]} | {v} |" for k, v in sorted(counts.items())]
    if diffs:
        lines += ["", "First differences:", ""] + [f"- {d['source']}: {d['old']} -> {d['new']}" for d in diffs[:20]]
    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
