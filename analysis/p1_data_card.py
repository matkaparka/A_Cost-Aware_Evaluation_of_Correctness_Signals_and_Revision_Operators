"""P1 data card (CLAUDE.md P1; design §5.3): data/processed + results/p1 -> reports/01_data_tables.md.

Dev: full statistics. Test: item counts and initial right/wrong counts per model x dataset only (pre-freeze rule).
Usage: python analysis/p1_data_card.py
"""
import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
P = ROOT / "data" / "processed"
OUT = ROOT / "reports" / "01_data_tables.md"


def jl(path):
    return [json.loads(line) for line in open(path, encoding="utf-8")]


def auroc(scores, labels):
    pos = [s for s, y in zip(scores, labels) if y]
    neg = [s for s, y in zip(scores, labels) if not y]
    if not pos or not neg:
        return None
    wins = sum((p > n) + 0.5 * (p == n) for p in pos for n in neg)
    return wins / (len(pos) * len(neg))


def latest(model, kind):
    """The newest synced run of this kind that is registered as done (superseded runs are skipped)."""
    reg = {r["run_id"]: r for r in jl(ROOT / "runs.jsonl")} if (ROOT / "runs.jsonl").exists() else {}
    runs = [p for p in (ROOT / "results" / "p1" / model).glob(f"p1-{kind}-{model}-*")
            if (p / "manifest.json").exists() and reg.get(p.name, {}).get("status") == "done"]
    runs.sort(key=lambda p: p.stat().st_mtime)
    return runs[-1] if runs else None


def main():
    lines = ["# P1 data tables (generated by analysis/p1_data_card.py; do not edit by hand)", ""]
    man = json.loads((P / "build_manifest.json").read_text())
    lines += ["## Sources (pinned revisions)", "", "| Dataset | Repo | Revision | Rows |", "|---|---|---|---|"]
    for name, m in man["sources"].items():
        lines.append(f"| {name} | {m['repo']} | `{m['revision'][:12]}` | {m['rows']} |")

    problems, merges = jl(P / "problems.jsonl"), jl(P / "merges.jsonl")
    split = json.loads((P / "split.json").read_text())
    kinds = Counter(f"{m['kind']} ({m['how']})" for m in merges)
    lines += ["", "## Canonical problems, links and merges", "",
              f"- Source rows: {sum(m['rows'] for m in man['sources'].values())}; canonical problems: {len(problems)}.",
              "- Unions: " + "; ".join(f"{k}: {v}" for k, v in sorted(kinds.items())) + " (every union is in `data/processed/merges.jsonl`).",
              f"- Fixed sets: spillover (test) {len(split['spillover_test'])}, KL probe (dev) {len(split['kl_dev'])}.", "",
              "| Stratum | Dev problems | Test problems |", "|---|---|---|"]
    c = Counter((p["stratum"], split["split"][p["canonical_id"]]) for p in problems)
    for s in sorted({p["stratum"] for p in problems}):
        lines.append(f"| {s} | {c[(s, 'dev')]} | {c[(s, 'test')]} |")

    lines += ["", "## Items per dataset and split", "", "| Table | Dataset | Dev | Test |", "|---|---|---|---|"]
    for table in ("dnat", "dinj", "exp0"):
        rows = jl(P / f"{table}.jsonl")
        cc = Counter((r.get("dataset", "exp0"), r["split"]) for r in rows)
        for ds in sorted({k[0] for k in cc}):
            lines.append(f"| {table} | {ds} | {cc[(ds, 'dev')]} | {cc[(ds, 'test')]} |")

    lines += ["", "## Initial answers a0 (greedy, non-thinking, vLLM batch-invariant)", "",
              "Test: counts of initially right and wrong items only (design §5.3).", "",
              "| Model | Dataset | Test n | Test right | Test wrong | Dev n | Dev acc | Dev unparsed | Dev truncated | Dev conflict |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    verbal_lines = ["", "## Verbal P(yes) on dev (pre-feedback; design §5.7)", "",
                    "| Model | Dataset | Dev n | AUROC for a0 correctness | Mean mass P(Y)+P(N) | First-token shortcut |",
                    "|---|---|---|---|---|---|"]
    for model in ("1.7B", "4B", "8B"):
        run = latest(model, "initial")
        if run is None:
            lines.append(f"| {model} | TODO(missing: initial answers) | | | | | | | | |")
            continue
        rows = jl(run / "initial.jsonl")
        by = defaultdict(list)
        for r in rows:
            by[(r["dataset"], r["split"])].append(r)
        for ds in ("gsm8k", "math500"):
            te, dv = by[(ds, "test")], by[(ds, "dev")]
            st = Counter(r["status"] for r in dv)
            lines.append(f"| {model} | {ds} | {len(te)} | {sum(r['correct'] for r in te)} | {sum(not r['correct'] for r in te)} | "
                         f"{len(dv)} | {sum(r['correct'] for r in dv) / len(dv):.3f} | {st['unparsed']} | {st['truncated']} | {st['conflict']} |")
        vrun = latest(model, "verbal")
        if vrun is not None:
            v = {r["item_id"]: r for r in jl(vrun / "verbal.jsonl")}
            vm = json.loads((vrun / "metrics.json").read_text())
            for ds in ("gsm8k", "math500"):
                dv = by[(ds, "dev")]
                sc = [v[r["item_id"]]["p_yes_norm"] for r in dv]
                a = auroc(sc, [r["correct"] for r in dv])
                mass = sum(v[r["item_id"]]["mass"] for r in dv) / len(dv)
                verbal_lines.append(f"| {model} | {ds} | {len(dv)} | {'—' if a is None else f'{a:.3f}'} | {mass:.3f} | {vm['first_token_shortcut']} |")
    lines += verbal_lines
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(OUT.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
