"""Verbal-readout check for the second family (DEVIATIONS D15; exploratory). Tulu-3-8B's verbal score is near chance on
test (reports/04_p4_T8B_tier1.md). This script tells a weak readout from a broken one: per model and split, the AUROC
of P(yes)_norm for a0 correctness, the yes/no probability mass at the verdict position (a broken render or token set
would put little mass there), and the mean P(yes)_norm on right and on wrong answers. Qwen3-8B is the reference.
Inputs: the p1 initial-answer and verbal files of each model (original pool and expansion).
-> reports/fu_04_verbal_check.md, analysis/out/fu_04_verbal_check.json
Usage: python analysis/fu_verbal_check.py
"""
import json
import sys
from pathlib import Path

import numpy as np
from sklearn.metrics import roc_auc_score

ROOT = Path(__file__).resolve().parents[1]
RUNS = {"T8B": [("results/fu2/p1/T8B/p1-initial-T8B-1809070", "results/fu2/p1/T8B/p1-verbal-T8B-1809070"),
                ("results/fu2/p1/T8B/p1-initial-ext-T8B-1809070", "results/fu2/p1/T8B/p1-verbal-ext-T8B-1809070")],
        "8B": [("results/p1/8B/p1-initial-8B-d2ebdea", "results/p1/8B/p1-verbal-8B-d2ebdea"),
               ("results/p1/8B/p1-initial-ext-8B-45575c2", "results/p1/8B/p1-verbal-ext-8B-45575c2")]}


def jl(p):
    return [json.loads(line) for line in open(p, encoding="utf-8")]


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    out = {}
    for m, pairs in RUNS.items():
        c, v = {}, []
        for ini, ver in pairs:
            c.update({r["item_id"]: bool(r["correct"]) for r in jl(ROOT / ini / "initial.jsonl")})
            v += jl(ROOT / ver / "verbal.jsonl")
        out[m] = {}
        for split in ("dev", "test"):
            rs = [r for r in v if r["split"] == split and r["item_id"] in c]
            y = np.array([c[r["item_id"]] for r in rs], float)
            s = np.array([r["p_yes_norm"] for r in rs])
            mass = np.array([r["mass"] for r in rs])
            out[m][split] = {"n": len(rs), "a0 accuracy": float(y.mean()), "auroc": float(roc_auc_score(y, s)),
                             "mass min": float(mass.min()), "mass median": float(np.median(mass)),
                             "share mass < 0.5": float((mass < 0.5).mean()),
                             "mean P(yes)_norm | right": float(s[y == 1].mean()),
                             "mean P(yes)_norm | wrong": float(s[y == 0].mean())}
    (ROOT / "analysis" / "out" / "fu_04_verbal_check.json").write_text(json.dumps(out, indent=1), encoding="utf-8",
                                                                       newline="\n")
    L = ["# Verbal-readout check, Tulu-3-8B vs Qwen3-8B (generated by analysis/fu_verbal_check.py)", "",
         "Exploratory (DEVIATIONS D15). Pooled original pool and expansion. Mass = P(yes) + P(no) over the candidate "
         "tokens at the verdict position.", "",
         "| Model | Split | n | a0 acc | AUROC | Mass min | Mass median | Mass < 0.5 | P(yes)_norm right | P(yes)_norm wrong |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for m, d in out.items():
        for split, r in d.items():
            L.append(f"| {m} | {split} | {r['n']} | {100 * r['a0 accuracy']:.1f} % | {r['auroc']:.3f} | {r['mass min']:.3f} | "
                     f"{r['mass median']:.3f} | {100 * r['share mass < 0.5']:.1f} % | {r['mean P(yes)_norm | right']:.3f} | "
                     f"{r['mean P(yes)_norm | wrong']:.3f} |")
    (ROOT / "reports" / "fu_04_verbal_check.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
