"""H2a power with the P3 D-nat expansion (design §5.1, §7.4): is the expansion needed, and does it suffice?
results/p1 + results/p2 (+ results/p3 probe) -> reports/03_power_h2a_tables.md, analysis/out/power_h2a_p3.json.

As analysis/p2_power_h2a.py (one-sided paired DeLong for AUROC(probe) > AUROC(verbal) at the first Holm step, as a
stand-in for the paired bootstrap; out-of-fold probe scores on dev at the selected layer and C), with two changes:
- the probe is selected on the enlarged dev (original dev + expansion dev; src/probe/train.py on both activation
  files), and its out-of-fold scores use the same grouped 5-fold CV;
- simulated test sets are drawn within (stratum, label) cells, stratum = original pool (GSM8K + MATH-500) or
  expansion (math_ext), with the test right/wrong counts of each cell. Scopes: the original pool only, and the
  original pool plus the expansion. Scenarios: the dev effect, half of it, and the central one, a probe AUROC DELTA_AUC
  above the verbal AUROC (calibrated noise on the probe score when the dev gap exceeds DELTA_AUC, otherwise on the
  verbal score).
Levels: alpha / 6 and alpha / 9 (Tier 1 with none / all of the Tier 2 hypotheses in the family).
Usage: python analysis/p3_power_h2a.py   (RUNS below pins every input run)
"""
import json
import math
from pathlib import Path

import numpy as np

from p2_power_h2a import delong_paired, noise_for_auc, oof_scores

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "reports" / "03_power_h2a_tables.md"
ALPHA, FAMILIES, SIMS, SEED = 0.05, (6, 9), 2000, 0
# Pinned inputs; the *_ext runs and the probe are filled in when they exist (TODO otherwise).
RUNS = {m: {"initial": f"p1-initial-{m}-d2ebdea", "verbal": f"p1-verbal-{m}-d2ebdea", "acts": f"p2-acts-dev-{m}-f7e5011",
            "initial_ext": f"p1-initial-ext-{m}-45575c2", "verbal_ext": f"p1-verbal-ext-{m}-45575c2",
            "acts_ext": f"p2-acts-dev-ext-{m}-8360990", "probe": f"p3-probe-dev-ext-{m}-b7cf0d6"} for m in ("4B", "1.7B")}
DELTA_AUC = 0.03   # H2a margin on the AUROC scale (DECISIONS 2026-11-04); the central scenario's effect


def jl(p):
    return [json.loads(l) for l in open(p, encoding="utf-8")]


def verbal_score(r):
    return math.log(max(r["p_yes"], 1e-300)) - math.log(max(r["p_no"], 1e-300))


def main():
    rng = np.random.default_rng(SEED)
    out = {}
    lines = ["# H2a power with the D-nat expansion (generated by analysis/p3_power_h2a.py; dev split only, test "
             "right/wrong counts)", "",
             "One-sided paired DeLong test of AUROC(probe) > AUROC(verbal), simulated test sets drawn from dev within "
             "(stratum, label) cells at the test counts of each cell; probe selected on the enlarged dev; dev AUROCs and scenario noise per scope (that scope's dev items). Power at α/6 and "
             "α/9 (first Holm step with none / all of the Tier 2 hypotheses in the family).", "",
             "| Model | Probe (layer, C) | Scope dev AUROC probe (OOF) | Scope dev AUROC verbal | Scope | Test right / wrong | Scenario | "
             "Power α/6 | Power α/9 |", "|---|---|---|---|---|---|---|---|---|"]
    items = {r["item_id"]: r for f in ("dnat.jsonl", "ext/dnat_ext.jsonl") for r in jl(ROOT / "data" / "processed" / f)}
    for model, run in RUNS.items():
        if not all(run.values()):
            lines.append(f"| {model} | TODO(missing: {', '.join(k for k, v in run.items() if not v)}) | | | | | | | |")
            continue
        P1, P2, P3 = (ROOT / "results" / e / model for e in ("p1", "p2", "p3"))
        sel = json.loads((P3 / run["probe"] / "probe_selection.json").read_text())["selected"]
        zs = [np.load(P2 / run[k] / "acts.npz") for k in ("acts", "acts_ext")]
        X = np.concatenate([z["X"][:, sel["layer"]].astype(np.float32) for z in zs])
        y = np.concatenate([z["correct0"].astype(int) for z in zs])
        ids = np.concatenate([z["ids"] for z in zs])
        groups = np.array([items[i]["canonical_id"] for i in ids])
        stratum = np.array([items[i].get("stratum") == "math_ext" for i in ids], int)
        p = oof_scores(X, y, groups, sel["C"])
        verbal = {r["item_id"]: r for k in ("verbal", "verbal_ext") for r in jl(P1 / run[k] / "verbal.jsonl")}
        v = np.array([verbal_score(verbal[i]) for i in ids])
        _, auc_p, auc_v = delong_paired(p, v, y)
        init = [r for k in ("initial", "initial_ext") for r in jl(P1 / run[k] / "initial.jsonl") if r["split"] == "test"]
        counts = {(s, c): sum((items[r["item_id"]].get("stratum") == "math_ext") == bool(s) and r["correct"] == c for r in init)
                  for s in (0, 1) for c in (True, False)}
        res = {"probe": sel, "dev_n": int(len(y)), "dev_auroc_probe_oof": auc_p, "dev_auroc_verbal": auc_v,
               "test_counts": {f"{'ext' if s else 'orig'}/{'right' if c else 'wrong'}": n for (s, c), n in counts.items()},
               "scopes": {}}
        for scope, strata in (("original pool", (0,)), ("original + expansion", (0, 1))):
            # Scenarios are calibrated on the dev items of the scope itself (its own dev gap and score distributions).
            mask = np.isin(stratum, strata)
            sub = np.full(len(y), -1)
            sub[mask] = np.arange(mask.sum())
            ps_, vs_, ys_ = p[mask], v[mask], y[mask]
            _, ap, av = delong_paired(ps_, vs_, ys_)
            zp, sigma = noise_for_auc(ps_, ys_, av + (ap - av) / 2, rng)
            zv = (vs_ - vs_.mean()) / vs_.std()
            # Central: AUROC(probe) - AUROC(verbal) = DELTA_AUC; noise on the probe when the dev gap is larger, otherwise
            # on the verbal score (lowering its AUROC to AUROC(probe) - DELTA_AUC; the probe score unchanged).
            central = (("probe", noise_for_auc(ps_, ys_, av + DELTA_AUC, rng)[1]) if ap - av > DELTA_AUC
                       else ("verbal", noise_for_auc(vs_, ys_, ap - DELTA_AUC, rng)[1]))
            res["scopes"][scope] = {"dev_n": int(mask.sum()), "dev_auroc_probe_oof": ap, "dev_auroc_verbal": av,
                                    "half_effect_noise_sigma": sigma, "central_noise": central, "scenarios": {}}
            n_r = sum(counts[(s, True)] for s in strata)
            n_w = sum(counts[(s, False)] for s in strata)
            for name, on, sd in (("dev effect", None, 0.0), ("half effect", "probe", sigma),
                                 (f"central (Δ AUROC = {DELTA_AUC}, noise on {central[0]})", *central)):
                pv = np.empty(SIMS)
                for k in range(SIMS):
                    idx = np.concatenate([rng.choice(np.where((stratum == s) & (y == int(c)))[0], counts[(s, c)])
                                          for s in strata for c in (True, False) if counts[(s, c)]])
                    j = sub[idx]
                    scores = zp[j] + sd * rng.standard_normal(len(j)) if on == "probe" else ps_[j]
                    vsc = zv[j] + sd * rng.standard_normal(len(j)) if on == "verbal" else vs_[j]
                    pv[k] = delong_paired(scores, vsc, ys_[j])[0]
                pw = {f: float((pv < ALPHA / f).mean()) for f in FAMILIES}
                res["scopes"][scope]["scenarios"][name] = pw
                lines.append(f"| {model} | {sel['layer']}, {sel['C']} | {ap:.3f} | {av:.3f} | {scope} | {n_r} / {n_w} | "
                             f"{name} | {pw[6]:.2f} | {pw[9]:.2f} |")
        out[model] = res
    (ROOT / "analysis" / "out" / "power_h2a_p3.json").write_text(json.dumps(out, indent=1))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(OUT.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
