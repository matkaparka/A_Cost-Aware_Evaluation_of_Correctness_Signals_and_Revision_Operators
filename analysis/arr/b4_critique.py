"""B4 of the ARR plan (docs/planning/arr_round/plan.md §B, B4; Amendment 2): the sample-aware critique.

Selection (analysis/arr/b4_select.py): the 20 % of items with the lowest vote margin over the first five samples,
gold-blind, ties by SHA-256(item_id). Each run keeps its own selection file (selection.jsonl), which this script
checks against A1's HYBRID-margin(20 %) membership.
Run: `samples-critique`, one greedy review turn after a0 (2,048 tokens), whose instruction shows the five samples'
final answers ("no final answer" for an invalid sample).
Settings: math Qwen3-1.7B, 4B, 8B, Tulu-3-8B (1.7B, 8B and T8B use their B1 samples) and MMLU-Pro Qwen3-4B, T8B (the
stored sample letters).

Labels: math, the common gold-blind rule (A0), two phases (extractions frozen and hashed before any gold is read);
MMLU-Pro, the frozen letter scorer (a missing letter at the token cap counts as truncated).

Analysis (plan B4): HYBRID-margin with this operator instead of F2, at 10 % (the lowest half of the run) and 20 %
(the whole run): items selected get the sample-aware critique's answer, all others V5; against V5 and KEEP, with
A1's HYBRID-margin (F2) beside it. Cost: the five samples for every item plus the critique on the selected items.

Usage: python -B analysis/arr/b4_critique.py  (after b1_samples.py)
-> analysis/out/arr/b4_extractions.jsonl.gz (frozen before gold), b4_labels.jsonl.gz, b4_critique.json,
   b4_critique_manifest.json; reports/arr_b4.md
"""
import json
import re
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import a1a2_replays as A  # noqa: E402
import b1_samples as B1  # noqa: E402
from common import (J1, MODELS_MATH, MODELS_MC, OUT, REPO, Boot, Equivalence, candidate, dump, guard_check, manifest, pin,  # noqa: E402
                    plan_core_hash, plan_hash, rows, rows_gz, sha, unique, write_rows_gz)
from src.score import mc as MC  # noqa: E402

SETTINGS = [("math", m) for m in MODELS_MATH] + [("mc", m) for m in MODELS_MC]


def verified(d, name):
    man = json.loads((d / "manifest.json").read_text(encoding="utf-8"))
    assert sha(d / name) == man["files"][name], ("manifest checksum", d.name, name)
    return pin(d / name), man


def b4_run(task, model):
    """The critique run of one setting, hash-checked: ({item: record}, selection rows, info) or (None, None, reason)."""
    root = REPO / "results" / "arr" / "b4" / model
    pat = re.compile(rf"^b4-samples-critique-{task}-test-{re.escape(model)}-([0-9a-f]{{7}})$")
    hits = {}
    for d in sorted(root.iterdir()) if root.exists() else []:
        m = pat.match(d.name)
        if m and (d / "manifest.json").exists():
            hits[m.group(1)] = d
    if not hits:
        return None, None, "no run synced"
    assert len(hits) == 1, ("B4 runs from more than one code commit (CLAUDE.md rule 8)", task, model, sorted(hits))
    (commit, d), = hits.items()
    cfg = json.loads(verified(d, "config.json")[0].read_text(encoding="utf-8"))
    assert (cfg["stage"], cfg["task"], cfg["model"], cfg["split"]) == ("samples-critique", task, model, "test"), d.name
    path_g, man = verified(d, "generations.jsonl")
    assert man["env"].get("VLLM_BATCH_INVARIANT") == "1" and man["code_commit"].startswith(commit), d.name
    gens = {g["prompt_key"]: g for g in rows(path_g)}
    selection = list(rows(verified(d, "selection.jsonl")[0]))
    out = {}
    for r in rows(verified(d, "rows.jsonl")[0]):
        assert r["cond"] == "F-samples" and r["item_id"] not in out
        g = gens[r["prompt_key"]]
        assert g["out_tokens"] == r["out_tokens"] and g["finish_reason"] == r["finish_reason"]
        out[r["item_id"]] = {"text": g["text"], "finish_reason": g["finish_reason"], "out_tokens": int(r["out_tokens"]),
                             "prompt_tokens": int(r["prompt_tokens"])}
    assert set(out) == {s["item_id"] for s in selection}, ("the run does not cover its selection", task, model)
    return out, selection, {"run": d.name, "run_commit": commit}


def extract(task, g, item, eq):
    if task == "math":
        c = candidate(g["text"], g["finish_reason"], g["out_tokens"], eq)
        return {f: c[f] for f in ("pred", "status", "raw_extraction_status")}
    pred, raw = MC.extract(g["text"], item)
    status = "ok" if pred is not None else ("truncated" if g["finish_reason"] == "length" else "unparsed")
    return {"pred": pred, "status": status, "raw_extraction_status": raw}


def fmt(ci):
    return f"{ci['estimate']:+.2f} [{ci['lo']:+.2f}, {ci['hi']:+.2f}]"


def report(res):
    L = ["# ARR round, B4: a critique that sees the samples' answers", "",
         f"Generated by `analysis/arr/b4_critique.py` (plan `docs/planning/arr_round/plan.md`, core sha256 "
         f"`{res['plan_core_sha256'][:16]}…`). Post hoc and exploratory (DEVIATIONS D20); added in revision.",
         "Δ in percentage points with paired 95 % cluster-bootstrap intervals (4,000 replicates, seed 20261110). "
         "HYBRID-margin-B4(s): the share s of items with the lowest vote margin gets the sample-aware critique, every other "
         "item V5. HYBRID-margin (F2) is A1's policy with the stored F2 critique of a0.", ""]
    missing = {s: v["status"] for s, v in res["settings"].items() if v["status"] != "complete"}
    if missing:
        L += ["Not yet complete: " + "; ".join(f"{s}: TODO(missing: {why})" for s, why in missing.items()) + ".", ""]
    L += ["| Setting | Policy | Acc. % | Δ vs KEEP | Δ vs V5 | Gen. tok/item |", "|---|---|---:|---:|---:|---:|"]
    for s, v in res["settings"].items():
        if v["status"] != "complete":
            continue
        for name, p in v["policies"].items():
            L.append(f"| {s} | {name} | {p['accuracy_pct']:.2f} | {fmt(p['delta_vs_keep'])} | "
                     f"{fmt(v['vs_v5'][name]) if name in v['vs_v5'] else '—'} | {p['generated_tokens_per_item']:.0f} |")
    L += ["", "| Setting | Contrast | Difference (pp) | Token difference |", "|---|---|---:|---:|"]
    for s, v in res["settings"].items():
        for c in v.get("contrasts", []):
            L.append(f"| {s} | {c['a']} − {c['b']} | {fmt(c['difference'])} | {c['token_difference']:+.0f} |")
    L += ["", "On the selected 20 % (correct answers, of the run's items):", ""]
    for s, v in res["settings"].items():
        if v["status"] == "complete":
            c = v["on_selected"]
            L.append(f"- {s}: {c['n']} items; a0 {c['a0']}, V5 {c['V5']}, F2 {c['F2']}, sample-aware critique {c['B4']} "
                     f"(no usable answer: {c['B4_unanswered']}).")
    L += ["", "Checks: " + "; ".join(res["checks"]) + ".", ""]
    (REPO / "reports" / "arr_b4.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")


def main():
    plan = plan_hash()
    a0 = json.loads(pin(OUT / "a0_common_labels.json").read_text(encoding="utf-8"))
    assert a0["plan_core_sha256"] == plan_core_hash() and not a0["guards"]
    labels = list(rows_gz(pin(OUT / "math_common_labels.jsonl.gz")))
    table = {}
    for r in rows(pin(J1 / "artifacts/math/item_evaluations.jsonl")):
        table.setdefault(r["model"], {}).setdefault(r["condition"], {})[r["item_id"]] = r
    math_pops = A.load_math(table, labels)
    mc_items = unique(rows(pin(REPO / "data/processed/mmlupro/items.jsonl")))
    res = {"plan_sha256_lf": plan, "plan_core_sha256": plan_core_hash(), "settings": {}, "checks": []}
    eq = Equivalence()
    try:
        pops, runs = {}, {}
        for task, model in SETTINGS:
            s = f"{'math' if task == 'math' else 'MMLU-Pro'} {model}"
            if task == "math":
                P = math_pops[model]
                S8 = B1.attach(P, model, eq)
                if S8 is None and model == "4B":
                    A.add_math_samples(P, eq)
                if "samples" not in P:
                    res["settings"][s] = {"status": "B1 samples not complete"}
                    continue
            else:
                P, S8 = A.load_mc(model), None
            out, selection, info = b4_run(task, model)
            if out is None:
                res["settings"][s] = {"status": f"B4 run: {info}"}
                continue
            # the run's selection is A1's HYBRID-margin(20 %) membership, and it showed the first five samples' answers
            sel20 = A.select(P["sig"]["margin"], P["tie"], 0.20)
            assert {P["ids"][j] for j in np.flatnonzero(sel20)} == {r["item_id"] for r in selection}, ("B4 selection", s)
            idx = {i: j for j, i in enumerate(P["ids"])}
            for r in selection:
                assert abs(r["margin"] - P["sig"]["margin"][idx[r["item_id"]]]) < 1e-12, ("B4 margin", s, r["item_id"])
                if S8 is not None:
                    shown = [c["pred"] if c["status"] == "ok" else None for c in S8["cands"][idx[r["item_id"]]][:5]]
                    assert shown == r["answers"], ("B4 answers shown", s, r["item_id"])
            res["checks"].append(f"{s}: the run's selection equals A1's HYBRID-margin(20 %) items and their margins"
                                 + (", and the answers shown equal the first five samples' candidates" if S8 is not None else ""))
            pops[s], runs[s] = (task, model, P), (out, info)
        extractions = []
        for s, (task, model, P) in pops.items():
            for i, g in sorted(runs[s][0].items()):
                item = {k: v for k, v in mc_items[i].items() if k != "gold"} if task == "mc" else None
                extractions.append({"setting": s, "item_id": i, **extract(task, g, item, eq),
                                    "out_tokens": g["out_tokens"], "prompt_tokens": g["prompt_tokens"], "finish_reason": g["finish_reason"]})
        frozen = OUT / "b4_extractions.jsonl.gz"
        write_rows_gz(frozen, extractions)
        frozen_hash = sha(frozen)
        print(f"extractions frozen: {len(extractions)} rows, sha256 {frozen_hash[:16]}", flush=True)
        gold = {r["item_id"]: r["gold"] for p in (pin(REPO / "data/processed/dnat.jsonl"),
                                                  pin(REPO / "data/processed/ext/dnat_ext.jsonl")) for r in rows(p)}
        for e in extractions:
            task = pops[e["setting"]][0]
            if e["status"] != "ok":
                e["correct"] = 0
            elif task == "math":
                e["correct"] = int(eq(e["pred"], gold[e["item_id"]]))
            else:
                e["correct"] = int(e["pred"] == mc_items[e["item_id"]]["gold"])
        guards = list(eq.guards)
    finally:
        eq.close()
    assert sha(frozen) == frozen_hash
    res["scorer_guards"] = guard_check(guards)
    write_rows_gz(OUT / "b4_labels.jsonl.gz", extractions)
    res["extractions_sha256_before_gold"] = frozen_hash
    for s, (task, model, P) in pops.items():
        lab = {e["item_id"]: e for e in extractions if e["setting"] == s}
        n = P["n"]
        S = P["samples"]
        inrun = np.array([i in lab for i in P["ids"]])
        yb = np.array([lab[i]["correct"] if i in lab else 0 for i in P["ids"]], dtype=float)
        gb = np.array([lab[i]["out_tokens"] if i in lab else 0 for i in P["ids"]], dtype=float)
        pb = np.array([lab[i]["prompt_tokens"] if i in lab else 0 for i in P["ids"]], dtype=float)
        ab = np.array([lab[i]["status"] == "ok" if i in lab else False for i in P["ids"]])
        v5y, v5a = S["vk_correct"][5], S["vk_answered"][5]
        tok5, pr5 = S["tok"].sum(axis=1), 5 * S["sprompt"]
        pol = A.policies(P)
        out = {"KEEP": pol["KEEP"], "V5": pol["V5"]}
        for share in A.SHARES:
            tag = f"{round(share * 100)}%"
            sel = A.select(P["sig"]["margin"], P["tie"], share)
            assert not (sel & ~inrun).any(), ("the 10 % selection lies inside the run", s)
            out[f"HYBRID-margin-B4 {tag}"] = A.Pol(np.where(sel, yb, v5y), tok5 + sel * gb, pr5 + sel * pb, np.where(sel, ab, v5a), sel)
            out[f"HYBRID-margin {tag}"] = pol[f"HYBRID-margin {tag}"]
        boot = Boot(P["canonical"])
        f2 = P["ops"]["F2"]
        res["settings"][s] = {
            "status": "complete", "n": n, "run": runs[s][1], "policies": A.describe(P, out, boot),
            "vs_v5": {k: boot.ci(p.y - v5y) for k, p in out.items() if k != "V5"},
            "contrasts": [{"a": a, "b": b, "difference": boot.ci(out[a].y - out[b].y),
                           "token_difference": float((out[a].gen - out[b].gen).mean())}
                          for a, b in (("HYBRID-margin-B4 20%", "HYBRID-margin 20%"), ("HYBRID-margin-B4 10%", "HYBRID-margin 10%"))],
            "on_selected": {"n": int(inrun.sum()), "a0": int(P["y0"][inrun].sum()), "V5": int(v5y[inrun].sum()),
                            "F2": int(f2["y1"][inrun].sum()), "B4": int(yb[inrun].sum()), "B4_unanswered": int((~ab[inrun]).sum())}}
    dump(OUT / "b4_critique.json", res)
    report(res)
    manifest("b4_critique", {"outputs": {p: sha(OUT / p) for p in ("b4_extractions.jsonl.gz", "b4_labels.jsonl.gz", "b4_critique.json")},
                             "settings_status": {s: v["status"] for s, v in res["settings"].items()}})
    print(json.dumps({s: v["status"] for s, v in res["settings"].items()}, indent=1))


if __name__ == "__main__":
    main()
