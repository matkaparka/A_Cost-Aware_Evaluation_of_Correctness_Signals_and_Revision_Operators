"""One-page summary of tier A of the ARR round, generated from the A0-A3 outputs (no new computation).

Usage: python -B analysis/arr/tier_a_summary.py -> reports/arr_tier_a.md
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import OUT, REPO, holm, p_floor, pfmt, plan_core_hash  # noqa: E402


def fmt(ci):
    return f"{ci['estimate']:+.2f} [{ci['lo']:+.2f}, {ci['hi']:+.2f}]"


def main():
    a0 = json.loads((OUT / "a0_common_labels.json").read_text(encoding="utf-8"))
    a1 = json.loads((OUT / "a1_policies.json").read_text(encoding="utf-8"))
    a3 = json.loads((OUT / "a3_dev_test.json").read_text(encoding="utf-8"))
    auroc = json.loads((OUT / "a2_auroc.json").read_text(encoding="utf-8"))
    assert a0["plan_core_sha256"] == a1["plan_core_sha256"] == a3["plan_core_sha256"] == plan_core_hash()
    S = a1["settings"]
    vote_settings = ["math 4B", "MMLU-Pro 4B", "MMLU-Pro T8B"]
    L = ["# ARR round, tier A summary (generated by `analysis/arr/tier_a_summary.py`)", "",
         "Post hoc and exploratory (DEVIATIONS D20; plan `docs/planning/arr_round/plan.md`). Stored outputs only. "
         "Δ in pp vs KEEP with paired 95 % cluster-bootstrap intervals; tokens are incremental generated tokens per item. "
         "Full tables: `reports/arr_a1_a2.md`, `reports/arr_a3.md`.", ""]
    changes = max(sum(v for v in m[c]["changed_hist_to_common"].values()) for m in a0["models"].values()
                  for c in ("initial", "F0", "F2", "F2-scratch"))
    L += [f"**A0.** One gold-blind scoring rule for a0, operators and votes in all four math models: at most {changes} label(s) "
          f"change per model and condition; Qwen3-4B reproduces the ACL same-rule labels ({a0['acl_4B_parity_checks']} checks).", "",
          "**Cheap baselines the paper lacks.**", "",
          "| Setting | KEEP acc. | F2 ALL | ANSWERLESS→F2 | ANSWERLESS→s1 | V1 (resample all) |", "|---|---:|---:|---:|---:|---:|"]
    for s in vote_settings:
        p = S[s]["policies"]
        cell = lambda k: f"{fmt(p[k]['delta_vs_keep'])}, {p[k]['generated_tokens_per_item']:.0f} tok"  # noqa: E731
        L.append(f"| {s} | {p['KEEP']['accuracy_pct']:.2f} % | {cell('F2 ALL')} | {cell('ANSWERLESS->F2')} | {cell('ANSWERLESS->s1')} | {cell('V1')} |")
    L += ["", "**Five samples: voting, gating, hybrids.**", "",
          "| Setting | V5 | GATE-a0 | STOP-2 | VOTE+a0 k5 | HYBRID-margin 20 % | AGREE→F2 20 % (paper) |", "|---|---:|---:|---:|---:|---:|---:|"]
    for s in vote_settings:
        p = S[s]["policies"]
        cell = lambda k: f"{fmt(p[k]['delta_vs_keep'])}, {p[k]['generated_tokens_per_item']:.0f} tok"  # noqa: E731
        L.append(f"| {s} | {cell('V5')} | {cell('GATE-a0')} | {cell('STOP-2')} | {cell('VOTE+a0 k5')} | {cell('HYBRID-margin 20%')} | {cell('AGREE->F2 20%')} |")
    L += ["", "**Where the gains come from.**", ""]
    for s in vote_settings:
        c = {(x["a"], x["b"]): x for x in S[s]["contrasts"]}
        f2 = S[s]["policies"]["F2 ALL"]
        L.append(f"- {s}: decoding V1 − KEEP {fmt(c[('V1', 'KEEP')]['difference'])}; aggregation V5 − V1 {fmt(c[('V5', 'V1')]['difference'])}; "
                 f"F2 ALL = completion {f2['repairs_completion']['estimate']:+.2f} + content {f2['repairs_content']['estimate']:+.2f} "
                 f"− format loss {f2['damage_format_loss']['estimate']:.2f} − content damage {f2['damage_content']['estimate']:.2f}.")
    tv = {a["signal"]: a for a in auroc if a["setting"] == "math T8B" and a["labels"] == "common"}["verbal"]
    L += ["", f"**AUROC pooling.** Tulu-3-8B math verbal: pooled {tv['pooled']:.3f}, within-source {tv['within_source']:.3f} "
          f"(per source " + ", ".join(f"{k} {v['auroc']:.3f}" for k, v in tv["per_source"].items()) + ").", "",
          "**A3, chosen on dev and evaluated on test.**", "",
          "| Setting | Rule | Policy | Test Δ vs KEEP | Joint re-selection CI | Regret (pp) |", "|---|---|---|---:|---:|---:|"]
    for s, o in a3["settings"].items():
        for rule, e in o["rules"].items():
            p, j = e["policy"], e["joint_reselection"]["test_delta_ci_pp"]
            L.append(f"| {s} | {rule} | {p['operator']}, {p['signal']}, {p['share_pct']} % | {fmt(e['test_delta_vs_keep'])} | "
                     f"[{j[0]:+.2f}, {j[1]:+.2f}] | {e['test_regret_pp']:.2f} |")
    fam = [dict(f) for f in a1["family_interim"]]
    for s, o in a3["settings"].items():
        e = o["rules"]["R1"]
        fam.append({"setting": s, "a": "A3 R1 policy", "b": "KEEP", "member": 5, "difference": e["test_delta_vs_keep"],
                    "p_boot": e["test_delta_vs_keep"]["p_boot"]})
    adj = holm({f"{f['setting']}|{f['a']}|{f['b']}": max(f["p_boot"], p_floor()) for f in fam})
    L += ["", f"**§5 family, members available after tier A ({len(fam)} contrasts; interim Holm — final Holm after B and C1).**", "",
          "p is two-sided from 4,000 paired bootstrap replicates; ≤0.0005 means no replicate crossed zero, and Holm uses 0.0005 for it.", "",
          "| Member | Setting | Contrast | Difference | p (boot) | Holm (interim) |", "|---:|---|---|---:|---:|---:|"]
    for f in sorted(fam, key=lambda f: (f["member"], f["setting"])):
        L.append(f"| {f['member']} | {f['setting']} | {f['a']} − {f['b']} | {fmt(f['difference'])} | {pfmt(f['p_boot'])} | "
                 f"{pfmt(adj[f['setting'] + '|' + f['a'] + '|' + f['b']])} |")
    L += ["", "Next: B and C1 runs need the new instance (STATUS); A3 for 8B and T8B math waits for B5.", ""]
    (REPO / "reports" / "arr_tier_a.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
