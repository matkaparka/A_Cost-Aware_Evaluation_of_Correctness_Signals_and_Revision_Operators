"""Plan Amendment 8 (docs/planning/arr_round/plan.md): thinking on every item under a budget B against selective
thinking at equal *total* generated tokens. Descriptive and post hoc; outside the §5 family; intervals as in §0 (paired
cluster bootstrap over canonical problems, 4,000 replicates, seed 20261110). Stored labels only: no generation, no
model, no extraction.

Why: Amendment 7 compares each uniform budget with the selective-THINK curve point nearest in cost after a0. A policy
that thinks on every item never needs a0, while a selective policy needs it for every item (the signal is read on it).
Here a0 is charged to the selective policy alone. The amendment was written after an ad hoc look at the mathematics
point estimates (stated there); this script is the full computation.

Definition (each C1 setting, budget B, signal in {verbal, probe}):
- U_B: generated tokens per item of the budget-B policy (its total; it does not use a0);
- A: mean generated tokens of a0 per item;
- the equal-total selective point: the largest share q on the 1-point grid with A + C(q) <= U_B, where C(q) is the C1
  curve's cost after a0; no interpolation; q = 0 is KEEP;
- reported: q, Δ vs KEEP with its CI, the total A + C(q), and the paired difference selective - uniform with its CI.

Inputs: c1_labels.jsonl.gz (C1) and c1b_labels.jsonl.gz (the forced answers of Amendment 7; an item without a row at
budget B reuses its C1 output), each checked against its manifest; the populations as c1_think.py loads them.
Parity checks: every rebuilt budget policy equals c1b_budget.json (accuracy, tokens, forced items); THINK ALL equals
c1_think.json; A equals b2_keep_strength.json for the mathematics settings.

Usage: python -B analysis/arr/c1_budget_total.py
-> analysis/out/arr/c1b_total.json, c1_budget_total_manifest.json (named after the script, as the package replay
   expects); reports/arr_c1_budget_total.md
"""
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from a1a2_replays import load_math, load_mc, select  # noqa: E402
from c1_think import SETTINGS, clean, curve, fmt, point_ci, score_of  # noqa: E402
from common import J1, OUT, REPO, Boot, dump, manifest, pin, plan_core_hash, plan_hash, rows, rows_gz, sha  # noqa: E402

BUDGETS = (256, 512, 1024, 2048)
SIGNALS = ("verbal", "probe")
STORED = {"c1_think": ("c1_labels.jsonl.gz", "c1_think.json"), "c1b_budget": ("c1b_labels.jsonl.gz", "c1b_budget.json"),
          "b2_keep_strength": ("b2_keep_strength.json",)}


def equal_total(P, T, yb, u, a0_tok, sig, cv, boot):
    """The largest share whose selective cost plus a0 fits the uniform budget's total, and its paired difference."""
    fits = [pt for pt in cv if a0_tok + pt["generated_tokens_per_item"] <= u + 1e-9]
    if not fits:   # a0 alone costs more than the uniform policy: no selective policy at this total
        return {"fits": False}
    pt = max(fits, key=lambda p: p["share_pct"])
    sel = select(score_of(P, sig, T["y"]), P["tie"], pt["share_pct"] / 100)
    assert int(sel.sum()) == pt["selected_n"], (P["setting"], sig, pt["share_pct"])
    gain = sel * (T["y"] - P["y0"])
    assert abs(100 * gain.mean() - pt["delta_pp"]) < 1e-9, (P["setting"], sig, pt["share_pct"])
    return {"fits": True, "share_pct": pt["share_pct"], "selected_n": pt["selected_n"],
            "delta_ci": point_ci(P, T["y"], sig, pt["share_pct"], boot),
            "selective_tokens_after_a0": pt["generated_tokens_per_item"],
            "total_tokens_per_item": a0_tok + pt["generated_tokens_per_item"],
            "selective_minus_uniform": boot.ci(gain - (yb - P["y0"]))}


def report(res):
    L = ["# ARR round, Amendment 8: uniform thinking budgets against selective thinking at equal total tokens", "",
         f"Generated by `analysis/arr/c1_budget_total.py` (plan `docs/planning/arr_round/plan.md`, core sha256 "
         f"`{res['plan_core_sha256'][:16]}…`). Descriptive and post hoc; outside the §5 family; written after an ad hoc "
         "look at the mathematics point estimates (see the amendment).",
         "Δ in percentage points vs KEEP, with paired 95 % cluster-bootstrap intervals (4,000 replicates, seed 20261110); "
         "the differences are unadjusted. A uniform budget's cost is its generated tokens per item (it does not use a0). "
         "A selective policy's cost is a0's tokens plus thinking on the selected items; the point shown is the largest "
         "share (1-point steps, no interpolation) whose total does not exceed the uniform budget's.", ""]
    for s, v in res["settings"].items():
        if v.get("status") != "complete":
            L += [f"## {s}", "", f"TODO(missing: {v.get('status')})", ""]
            continue
        L += [f"## {s} (n = {v['n']}; a0: {v['a0_tokens_per_item']:.0f} generated tokens per item)", "",
              "| B | Uniform: Δ vs KEEP | Total tok | Signal | Share | Selective: Δ vs KEEP | Total tok | Selective − uniform |",
              "|---:|---:|---:|---|---:|---:|---:|---:|"]
        for b in BUDGETS:
            r = v["budgets"][str(b)]
            for k, sig in enumerate(SIGNALS):
                e = r["equal_total_selective"][sig]
                head = (f"| {b} | {fmt(r['uniform']['delta_vs_keep'])} | {r['uniform']['total_tokens_per_item']:.0f} "
                        if k == 0 else "| | | ")
                if not e["fits"]:
                    L.append(head + f"| {sig} | — | a0 alone exceeds the budget's cost | | |")
                else:
                    L.append(head + f"| {sig} | {e['share_pct']} % | {fmt(e['delta_ci'])} | {e['total_tokens_per_item']:.0f} | "
                             f"{fmt(e['selective_minus_uniform'])} |")
        L.append("")
    L += ["## Checks", ""] + [f"- {c}" for c in res["checks"]] + [""]
    (REPO / "reports" / "arr_c1_budget_total.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")


def main():
    plan = plan_hash()
    assert b"### Amendment 8" in (REPO / "docs/planning/arr_round/plan.md").read_bytes(), "Amendment 8 is not in the plan"
    a0 = json.loads(pin(OUT / "a0_common_labels.json").read_text(encoding="utf-8"))
    assert a0["plan_core_sha256"] == plan_core_hash() and not a0["guards"]
    for name, files in STORED.items():   # stored outputs, each as its own manifest recorded it
        man = json.loads((OUT / f"{name}_manifest.json").read_text(encoding="utf-8"))
        for f in files:
            assert sha(OUT / f) == man["outputs"][f], f"{f} differs from {name}_manifest.json"
    c1 = json.loads(pin(OUT / "c1_think.json").read_text(encoding="utf-8"))
    c1b = json.loads(pin(OUT / "c1b_budget.json").read_text(encoding="utf-8"))
    b2 = json.loads(pin(OUT / "b2_keep_strength.json").read_text(encoding="utf-8"))
    assert c1b["budgets"] == list(BUDGETS) and c1b["signals"] == list(SIGNALS)
    c1_lab, forced = {}, {}
    for e in rows_gz(pin(OUT / "c1_labels.jsonl.gz")):
        if e["source"] == "C1":
            c1_lab.setdefault(e["setting"], {})[e["item_id"]] = e
    for e in rows_gz(pin(OUT / "c1b_labels.jsonl.gz")):
        key = (e["setting"], int(e["budget"]))
        assert e["item_id"] not in forced.setdefault(key, {}), ("duplicate forced row", key, e["item_id"])
        forced[key][e["item_id"]] = e
    labels = list(rows_gz(pin(OUT / "math_common_labels.jsonl.gz")))
    table = {}
    for r in rows(pin(J1 / "artifacts/math/item_evaluations.jsonl")):
        table.setdefault(r["model"], {}).setdefault(r["condition"], {})[r["item_id"]] = r
    math_pops = load_math(table, labels)
    pops = {"math 4B": math_pops["4B"], "math 8B": math_pops["8B"], "MMLU-Pro 4B": load_mc("4B")}

    res = {"plan_sha256_lf": plan, "plan_core_sha256": plan_core_hash(), "budgets": list(BUDGETS),
           "signals": list(SIGNALS), "settings": {}, "checks": []}
    for s in SETTINGS:
        ref = c1b["settings"].get(s) or {}
        if ref.get("status") != "complete":
            res["settings"][s] = {"status": f"Amendment 7 output: {ref.get('status', 'missing')}"}
            continue
        P, lab = pops[s], c1_lab[s]
        assert set(lab) == set(P["ids"]), s
        T = {"y": np.array([lab[i]["correct"] for i in P["ids"]], dtype=float),
             "gen": np.array([lab[i]["out_tokens"] for i in P["ids"]], dtype=float)}
        ta = c1["settings"][s]["policies"]["THINK ALL"]
        assert abs(ta["accuracy_pct"] - 100 * T["y"].mean()) < 1e-9 and abs(ta["generated_tokens_per_item"] - T["gen"].mean()) < 1e-9, s
        a0_tok = float(-P["sig"]["length"].mean())
        if s in b2["settings"]:
            assert abs(b2["settings"][s]["a0_tokens_per_item"] - a0_tok) < 1e-9, s
        boot = Boot(P["canonical"])
        curves = {sig: curve(P, T["y"], T["gen"], sig) for sig in SIGNALS}
        entry = {"status": "complete", "n": P["n"], "a0_tokens_per_item": a0_tok,
                 "a0_checked_against_b2": s in b2["settings"], "budgets": {}}
        for b in BUDGETS:
            fb = forced.get((s, b), {})
            assert set(fb) <= set(P["ids"]), (s, b)
            src = [fb.get(i, lab[i]) for i in P["ids"]]
            yb = np.array([e["correct"] for e in src], dtype=float)
            gb = np.array([e["out_tokens"] for e in src], dtype=float)
            r = ref["budgets"][str(b)]
            assert abs(r["accuracy_pct"] - 100 * yb.mean()) < 1e-9 and abs(r["generated_tokens_per_item"] - gb.mean()) < 1e-9 \
                and r["forced_items"] == len(fb), ("the rebuilt budget policy differs from c1b_budget.json", s, b)
            u = float(gb.mean())
            uni = boot.ci(yb - P["y0"])
            assert abs(uni["estimate"] - r["delta_vs_keep"]["estimate"]) < 1e-9 and abs(uni["lo"] - r["delta_vs_keep"]["lo"]) < 1e-9, (s, b)
            entry["budgets"][str(b)] = {
                "uniform": {"delta_vs_keep": uni, "total_tokens_per_item": u},
                "equal_total_selective": {sig: equal_total(P, T, yb, u, a0_tok, sig, curves[sig], boot) for sig in SIGNALS}}
        res["settings"][s] = entry
        res["checks"].append(f"{s}: the four rebuilt budget policies equal `c1b_budget.json` (accuracy, tokens, forced items, "
                             f"Δ and its interval); THINK ALL equals `c1_think.json`; a0 tokens per item "
                             + ("equal `b2_keep_strength.json`." if s in b2["settings"] else
                                "are the mean of `initial_output_tokens` (B2 has no MMLU-Pro entry to compare with)."))
    res = clean(res)
    dump(OUT / "c1b_total.json", res)
    report(res)
    manifest("c1_budget_total", {"outputs": {"c1b_total.json": sha(OUT / "c1b_total.json")}})
    show = {s: {b: {sig: (e["share_pct"], round(e["selective_minus_uniform"]["estimate"], 2)) if e["fits"] else None
                    for sig, e in r["equal_total_selective"].items()} for b, r in v["budgets"].items()}
            for s, v in res["settings"].items() if v.get("budgets")}
    print(json.dumps(show, indent=1))


if __name__ == "__main__":
    main()
