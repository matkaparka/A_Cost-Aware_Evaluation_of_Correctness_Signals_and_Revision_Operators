"""B2 of the ARR plan (docs/planning/arr_round/plan.md §B, B2; Amendment 2): how strong is KEEP?

Runs (test; Amendment 2):
- (a) a0-long: one sampled a0 per item with an 8,192-token budget (Qwen3 recommended non-thinking sampling), the
  `samples --k 1 --stream a0-long --max-tokens 8192` run (results/arr/b1/<model>/b1-samples-test-k1-a0-long-t8192-...);
- (b) a0-cont: every a0 that stopped at the 4,096-token cap, continued greedily for up to 4,096 more tokens
  (results/arr/b2/<model>/b2-continue-test-x4096-...). The analysis scores a0 together with its continuation; an a0
  that was not truncated is its own a0-cont.
The dev runs of B2 are not used here (the plan's B2 analysis is on test).

Labels: the common gold-blind rule (A0), two phases: every extraction is written and hashed before any gold is read.

Analysis (plan B2):
- a0-long and a0-cont accuracy, Δ vs KEEP, and their token costs;
- Δ of every A1 policy (operators, selections, votes where samples exist) and of the A2 selection grid at 10 % and 20 %
  measured against a0-long and a0-cont instead of KEEP: are the gains only "more tokens"?;
- the completion share of the gains after continuation: each policy's repairs against a0-cont split by whether
  a0-cont has a usable answer (completion) or not (content), beside the same split against KEEP.

Usage: python -B analysis/arr/b2_keep_strength.py  (after b1_samples.py, whose samples it reuses where complete)
-> analysis/out/arr/b2_extractions.jsonl.gz (frozen before gold), b2_labels.jsonl.gz, b2_keep_strength.json,
   b2_keep_strength_manifest.json; reports/arr_b2.md
"""
