"""A3 for Qwen3-8B and Tulu-3-8B after B5 (docs/planning/arr_round/plan.md §A3 and §B5; Amendment 4).

The A3 rules are those of analysis/arr/a3_dev_test.py, unchanged (its grid, R1/R2 choice, share and threshold
transfer, regret, joint dev+test re-selection). Only the dev inventory is new (Amendment 4):
- operators F0, F2 and F2-scratch on dev from the B5 run (both turns' tokens from the run's rows);
- verbal: the dev rows of the P1 verbal runs; length;
- agreement, margin and s1 from the first five B1 dev samples (the ACL gold-blind agreement; complete-link groups);
- no probe: the stored dev activations are incomplete for 8B and absent for T8B.
The test side uses the same signals: A1's verbal and length, and agreement and margin from the B1 test samples.

Labels: the common gold-blind rule (A0), two phases: all dev extractions are frozen and hashed before any gold is read.
Usage: python -B analysis/arr/a3_b5.py  (after b1_samples.py)
-> analysis/out/arr/a3_b5_extractions.jsonl.gz, a3_b5_labels.jsonl.gz, a3_b5.json, a3_b5_grid.csv,
   a3_b5_manifest.json; reports/arr_a3_b5.md
"""
