MODELS = ("8B", "T8B")
K = 5
SIGNALS = ["verbal", "length", "agreement", "margin"]


def verified(d, name):
    man = json.loads((d / "manifest.json").read_text(encoding="utf-8"))
    assert sha(d / name) == man["files"][name], ("manifest checksum", d.name, name)
    return pin(d / name), man


def one_run(exp, model, pattern, cfg_expect, names):
    root = REPO / "results" / "arr" / exp / model
    pat = re.compile(pattern)
    hits = {}
    for d in sorted(root.iterdir()) if root.exists() else []:
        m = pat.match(d.name)
        if m and (d / "manifest.json").exists():
            hits[m.group(1)] = d
    if not hits:
        return None, "no run synced"
    assert len(hits) == 1, ("runs from more than one code commit (CLAUDE.md rule 8)", exp, model, sorted(hits))
    (commit, d), = hits.items()
    cfg = json.loads(verified(d, "config.json")[0].read_text(encoding="utf-8"))
    for k, v in cfg_expect.items():
        assert cfg[k] == v, (d.name, k, cfg[k], v)
    paths = {}
    for name in names:
        paths[name], man = verified(d, name)
        assert man["env"].get("VLLM_BATCH_INVARIANT") == "1" and man["code_commit"].startswith(commit), d.name
    return paths, {"run": d.name, "run_commit": commit}


def sources(table, model, split):
    """a0 rows and verbal rows of one split from the P1 runs named in the item table (the test a0's runs hold both splits)."""
    init_runs = sorted({r["initial_run"] for r in table[model]["F2"].values()})
    init, verbal = {}, {}
    for run in init_runs:
        for r in rows(A3.verified(run_dir(run), "initial.jsonl")):
            if r["split"] == split:
                assert r["item_id"] not in init
                init[r["item_id"]] = r
        vrun = run.replace("-initial-", "-verbal-")
        for r in rows(A3.verified(run_dir(vrun), "verbal.jsonl")):
            if r["split"] == split:
                verbal[r["item_id"]] = r
    return init, verbal, init_runs


def fmt(ci):
    return f"{ci['estimate']:+.2f} [{ci['lo']:+.2f}, {ci['hi']:+.2f}]"


def report(res):
    L = ["# ARR round, A3 for Qwen3-8B and Tulu-3-8B (after B5)", "",
         "Generated by `analysis/arr/a3_b5.py` (plan `docs/planning/arr_round/plan.md` §A3, §B5, Amendment 4). Post hoc and "
         "exploratory (DEVIATIONS D20); added in revision. The rules are those of `analysis/arr/a3_dev_test.py`, unchanged; "
         "signals: verbal, length, agreement and margin (no probe: Amendment 4).", ""]
    missing = {s: v for s, v in res["status"].items() if v != "complete"}
    if missing:
        L += ["Not yet complete: " + "; ".join(f"math {m}: TODO(missing: {why})" for m, why in missing.items()) + ".", ""]
    L += ["| Setting | Rule | Policy (operator, signal, share) | Dev Δ | Test Δ vs KEEP | Test Δ vs operator ALL | Threshold transfer | "
          "Joint re-selection CI | Test rank / grid | Regret | Gen. tok/item (test) |", "|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for s, o in res["settings"].items():
        for rule, e in o["rules"].items():
            p = e["policy"]
            thr = fmt(e["threshold_transfer"]["test_delta_vs_keep"]) if "threshold_transfer" in e else "—"
            vsall = fmt(e["test_delta_vs_operator_all"]) if "test_delta_vs_operator_all" in e else "—"
            j = e["joint_reselection"]["test_delta_ci_pp"]
            L.append(f"| {s} | {rule} | {p['operator']}, {p['signal']}, {p['share_pct']} % | {e['dev_delta_pp']:+.2f} | "
                     f"{fmt(e['test_delta_vs_keep'])} | {vsall} | {thr} | [{j[0]:+.2f}, {j[1]:+.2f}] | "
                     f"{e['test_rank']} / {o['grid_size']} | {e['test_regret_pp']:.2f} | {e['test_generated_tokens']:.0f} |")
    L += ["", "Parity: " + "; ".join(res["parity"]) + ".", ""]
    (REPO / "reports" / "arr_a3_b5.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")


def main():
    plan = plan_hash()
    a0 = json.loads(pin(OUT / "a0_common_labels.json").read_text(encoding="utf-8"))
    assert a0["plan_core_sha256"] == plan_core_hash() and not a0["guards"]
    data = unique(r for p in (pin(REPO / "data/processed/dnat.jsonl"), pin(REPO / "data/processed/ext/dnat_ext.jsonl")) for r in rows(p))
    labels = list(rows_gz(pin(OUT / "math_common_labels.jsonl.gz")))
    table = {}
    for r in rows(pin(J1 / "artifacts/math/item_evaluations.jsonl")):
        table.setdefault(r["model"], {}).setdefault(r["condition"], {})[r["item_id"]] = r
    test = A.load_math(table, labels)
    status, runs, parity = {}, {}, []
    for model in MODELS:
        ops, oi = one_run("b5-dev", model, rf"^b5-dev-ops-dev-main-F0\+F2\+F2-scratch-{re.escape(model)}-([0-9a-f]{{7}})$",
                          {"stage": "ops", "model": model, "split": "dev", "wording": "main", "conds": "F0,F2,F2-scratch"},
                          ("rows.jsonl", "generations.jsonl"))
        smp, si = one_run("b1-dev", model, rf"^b1-dev-samples-dev-k5-h2a-consistency-t4096-{re.escape(model)}-([0-9a-f]{{7}})$",
                          {"stage": "samples", "model": model, "split": "dev", "k": 5, "stream": "h2a-consistency"},
                          ("samples.jsonl",))
        if ops is None or smp is None:
            status[model] = "; ".join(f"{n}: {why}" for n, p, why in (("B5", ops, oi), ("B1 dev k5", smp, si)) if p is None)
            continue
        status[model] = "complete"
        runs[model] = {"ops": (ops, oi), "samples": (smp, si)}
    eq = Equivalence()
    try:
        recs_all, dev_inputs = [], {}
        for model, R in runs.items():
            init, verbal, init_runs = sources(table, model, "dev")
            # parity on test: the verbal scores this code reads equal A1's
            init_t, verbal_t, _ = sources(table, model, "test")
            assert np.allclose([verbal_s(verbal_t[i]) for i in test[model]["ids"]], test[model]["sig"]["verbal"], rtol=0, atol=1e-9)
            parity.append(f"math {model} test: verbal scores read by this code equal A1's")
            ids = sorted(init)
            assert len(ids) == 1264 and set(verbal) >= set(ids), (model, len(ids))
            gens = {g["prompt_key"]: g for g in rows(R["ops"][0]["generations.jsonl"])}
            ops = {}
            for r in rows(R["ops"][0]["rows.jsonl"]):
                if r["cond"] in OPS:
                    assert (r["item_id"], r["cond"]) not in ops
                    ops[(r["item_id"], r["cond"])] = r
            assert set(ops) == {(i, c) for i in ids for c in OPS}, ("B5 covers every dev item and operator", model)
            samples = unique(rows(R["samples"][0]["samples.jsonl"]))
            assert set(samples) == set(ids), ("B1 dev samples cover the dev pool", model)
            for i in ids:
                a = init[i]
                rec = {"model": model, "item_id": i, "canonical_id": a["canonical_id"], "dataset": a["dataset"],
                       "initial": {**{k: v for k, v in candidate(a["a0"], a["finish_reason"], len(a["a0_token_ids"]), eq).items()
                                      if k != "final_boxes"}, "hist_correct": int(a["correct"])}}
                for c in OPS:
                    r = ops[(i, c)]
                    g = gens[r["prompt_key"]]
                    assert g["out_tokens"] == r["out_tokens"] and g["finish_reason"] == r["finish_reason"]
                    assert (c == "F0") == ("turn1_out_tokens" not in r)
                    rec[c] = {**{k: v for k, v in candidate(g["text"], g["finish_reason"], g["out_tokens"], eq).items() if k != "final_boxes"},
                              "gen": r["out_tokens"] + r.get("turn1_out_tokens", 0), "prompt": r["prompt_tokens"] + r.get("turn1_prompt_tokens", 0)}
                cands = [candidate(s["text"], s["finish_reason"], s["out_tokens"], eq) for s in samples[i]["samples"]]
                assert len(cands) == K
                rec["samples"] = [{k: c[k] for k in ("pred", "status", "out_tokens")} for c in cands]
                rec["groups"] = groups_of(cands, lambda x, y, c=cands: eq.symmetric(c[x]["pred"], c[y]["pred"]))
                rec["agreement"] = sum(eq(c["pred"], rec["initial"]["pred"]) for c in cands) / K
                rec["verbal"] = verbal_s(verbal[i])
                rec["length"] = -len(a["a0_token_ids"])
                recs_all.append(rec)
            dev_inputs[model] = {"initial_runs": init_runs, "ops": R["ops"][1], "samples": R["samples"][1]}
        frozen = OUT / "a3_b5_extractions.jsonl.gz"
        write_rows_gz(frozen, recs_all)
        frozen_hash = sha(frozen)
        for r in recs_all:
            gold = data[r["item_id"]]["gold"]
            assert data[r["item_id"]]["split"] == "dev"
            for c in ("initial",) + OPS:
                r[c]["correct"] = int(r[c]["status"] == "ok" and eq(r[c]["pred"], gold))
            for s in r["samples"]:
                s["correct"] = int(s["status"] == "ok" and eq(s["pred"], gold))
        write_rows_gz(OUT / "a3_b5_labels.jsonl.gz", recs_all)
        results = {"plan_sha256_lf": plan, "plan_core_sha256": plan_core_hash(), "extractions_sha256_before_gold": frozen_hash,
                   "status": status, "dev_inputs": dev_inputs, "parity": parity, "settings": {}}
        grid_rows = []
        boot_test = Boot(test["4B"]["canonical"])
        for model in runs:
            recs = [r for r in recs_all if r["model"] == model]
            P = A3.math_dev_population(model, recs, probe=np.zeros(len(recs)), samples=True)
            del P["sig"]["probe"]
            T = test[model]
            assert B1.attach(T, model, eq) is not None, ("B1 test samples are needed on the test side", model)
            out, g = A3.a3_setting(P, T, SIGNALS, Boot(P["canonical"], seed=SEED + 1), boot_test)
            results["settings"][f"math {model}"] = out
            grid_rows += g
        guards = list(eq.guards)
    finally:
        eq.close()
    assert sha(frozen) == frozen_hash
    results["scorer_guards"] = guard_check(guards)
    dump(OUT / "a3_b5.json", results)
    if grid_rows:
        with (OUT / "a3_b5_grid.csv").open("w", encoding="utf-8", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(grid_rows[0]), lineterminator="\n")
            w.writeheader()
            w.writerows(grid_rows)
    report(results)
    outs = ["a3_b5_extractions.jsonl.gz", "a3_b5_labels.jsonl.gz", "a3_b5.json"] + (["a3_b5_grid.csv"] if grid_rows else [])
    manifest("a3_b5", {"outputs": {p: sha(OUT / p) for p in outs}, "settings_status": status})
    print(json.dumps({"status": status, "rules": {s: {r: (v["policy"], round(v["test_delta_vs_keep"]["estimate"], 2))
                                                      for r, v in o["rules"].items()} for s, o in results["settings"].items()}}, indent=1))


if __name__ == "__main__":
    main()
