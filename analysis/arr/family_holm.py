"""§5 of the ARR plan (docs/planning/arr_round/plan.md §5; Amendment 4): the declared family and its Holm correction.

Members (each two-sided, bootstrap p of §0, evaluated in every setting where its inputs exist):
1. HYBRID-margin(20 %) − V5            (A1: math 4B, MMLU-Pro 4B, T8B; B1: math 1.7B, 8B, T8B)
2. VOTE+a0(k = 5) − V5                  (same sources as 1)
3. RESAMPLE-ALL (= V1) − F2 ALL         (same sources as 1)
4. ANSWERLESS→F2 − F2 ALL               (A1: all six settings)
5. A3 rule R1's policy − KEEP (test)    (A3: math 1.7B, 4B, MMLU-Pro 4B, T8B; A3 after B5: math 8B, T8B)
6. C1: probe's selective THINK at 20 % − verbal's selective THINK at 20 %   (C1: math 4B, math 8B, MMLU-Pro 4B)
7. C1: THINK ALL − KEEP                 (same as 6)
With every run complete this is 36 contrasts (Amendment 4). Holm runs over the members present; a p of 0 enters as
the resolution floor 2/4000. The family is final only when all 36 are present; otherwise the output says "interim"
and lists the missing members as TODO(missing).

Usage: python -B analysis/arr/family_holm.py  (after a1a2_replays, b1_samples, a3_dev_test, a3_b5, c1_think)
-> analysis/out/arr/family_holm.json, family_holm_manifest.json; reports/arr_family.md
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import OUT, REPO, dump, holm, manifest, p_floor, pfmt, pin, plan_core_hash, plan_hash, sha  # noqa: E402

SETTINGS = ("math 1.7B", "math 4B", "math 8B", "math T8B", "MMLU-Pro 4B", "MMLU-Pro T8B")
CONTRASTS = {1: ("HYBRID-margin 20%", "V5"), 2: ("VOTE+a0 k5", "V5"), 3: ("V1", "F2 ALL"), 4: ("ANSWERLESS->F2", "F2 ALL"),
             5: ("A3 R1 policy", "KEEP"), 6: ("THINK by probe 20%", "THINK by verbal 20%"), 7: ("THINK ALL", "KEEP")}
EXPECTED = {(m, s) for s in SETTINGS for m in (1, 2, 3, 4, 5)} | {(m, s) for s in ("math 4B", "math 8B", "MMLU-Pro 4B") for m in (6, 7)}


def checked(output, manifest_name):
    """An analysis output, checked against its manifest (output hash, frozen plan core); None when it does not exist."""
    path, man_path = OUT / output, OUT / f"{manifest_name}_manifest.json"
    if not (path.exists() and man_path.exists()):
        return None
    man = json.loads(man_path.read_text(encoding="utf-8"))
    assert man["plan_core_sha256"] == plan_core_hash(), (output, "plan core differs")
    assert sha(path) == man["outputs"][output], (output, "output differs from its manifest")
    return json.loads(pin(path).read_text(encoding="utf-8"))


def fmt(ci):
    return f"{ci['estimate']:+.2f} [{ci['lo']:+.2f}, {ci['hi']:+.2f}]"


def main():
    plan = plan_hash()
    found = {}

    def add(member, setting, diff, source, note=None):
        key = (member, setting)
        assert key in EXPECTED, ("not a declared member", key)
        assert key not in found, ("member found twice", key)
        found[key] = {"member": member, "setting": setting, "a": CONTRASTS[member][0], "b": CONTRASTS[member][1],
                      "difference": diff, "p_boot": diff["p_boot"], "source": source, **({"note": note} if note else {})}

    a1 = checked("a1_policies.json", "a1a2_replays")
    assert a1 is not None, "tier A must exist"
    for f in a1["family_interim"]:
        add(f["member"], f["setting"], f["difference"], "A1 (a1_policies.json)")
    b1 = checked("b1_policies.json", "b1_samples")
    for f in (b1 or {}).get("family", []):
        add(f["member"], f["setting"], f["difference"], "B1 (b1_policies.json)")
    for name, source in (("a3_dev_test", "A3 (a3_dev_test.json)"), ("a3_b5", "A3 after B5 (a3_b5.json)")):
        res = checked(f"{name}.json", name)
        for s, o in (res or {}).get("settings", {}).items():
            r1 = o["rules"]["R1"]
            p = r1["policy"]
            add(5, s, r1["test_delta_vs_keep"], source, note=f"R1 policy: {p['operator']}, {p['signal']}, {p['share_pct']} %")
    c1 = checked("c1_think.json", "c1_think")
    for f in (c1 or {}).get("family", []):
        add(f["member"], f["setting"], f["difference"], "C1 (c1_think.json)")
    members = [found[k] for k in sorted(found, key=lambda k: (k[0], SETTINGS.index(k[1])))]
    adj = holm({f"{m['member']}|{m['setting']}": max(m["p_boot"], p_floor()) for m in members})
    for m in members:
        m["holm_p"] = adj[f"{m['member']}|{m['setting']}"]
        m["holm_reject_0.05"] = m["holm_p"] < 0.05
    missing = sorted(EXPECTED - set(found), key=lambda k: (k[0], SETTINGS.index(k[1])))
    res = {"plan_sha256_lf": plan, "plan_core_sha256": plan_core_hash(), "final": not missing, "present": len(members),
           "expected": len(EXPECTED), "missing": [{"member": m, "setting": s} for m, s in missing], "members": members}
    dump(OUT / "family_holm.json", res)
    L = ["# ARR round, §5: the declared family with Holm's correction", "",
         f"Generated by `analysis/arr/family_holm.py` (plan core sha256 `{res['plan_core_sha256'][:16]}…`). Post hoc and exploratory "
         "(DEVIATIONS D20). Two-sided paired cluster-bootstrap p (4,000 replicates); a bootstrap p of 0 enters Holm as 2/4000. "
         "Only the contrasts below may be called significant, and only by their Holm-adjusted p.", "",
         ("**Final**: all 36 declared contrasts are present." if res["final"] else
          f"**Interim**: {len(members)} of {len(EXPECTED)} declared contrasts are present; Holm over these only. Missing: "
          + "; ".join(f"member {m} in {s}: TODO(missing)" for m, s in missing) + "."), "",
         "| Member | Setting | Contrast | Difference (pp) | p (boot) | Holm p | Holm α = 0.05 | Source |",
         "|---:|---|---|---:|---:|---:|---|---|"]
    for m in members:
        L.append(f"| {m['member']} | {m['setting']} | {m['a']} − {m['b']}{' (' + m['note'] + ')' if 'note' in m else ''} | "
                 f"{fmt(m['difference'])} | {pfmt(m['p_boot'])} | {pfmt(m['holm_p'])} | "
                 f"{'reject' if m['holm_reject_0.05'] else 'do not reject'} | {m['source']} |")
    (REPO / "reports" / "arr_family.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    manifest("family_holm", {"outputs": {"family_holm.json": sha(OUT / "family_holm.json")}, "final": res["final"]})
    print(json.dumps({"final": res["final"], "present": len(members), "expected": len(EXPECTED),
                      "rejected": sum(m["holm_reject_0.05"] for m in members)}, indent=1))


if __name__ == "__main__":
    main()
