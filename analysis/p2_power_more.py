"""Power for the Tier 1 and Tier 2 tests not covered by analysis/power.py (design §7.4): H1b, H3a-role and
H3a-label with their pre-registered estimands, and H2b. Dev pilots only -> reports/02_power_more_tables.md,
analysis/out/power_more.json.

- H1b: one-sided GEE slope of correctness on p in {0.5, 0.7, 0.9, 1.0}, clustered by item (stats.gee_slope). Items
  are resampled from the dev pilot (each with its four outcomes). Scenarios: the pilot slope, and half of it (each
  resampled item, with probability 1/2, has its four outcomes shuffled across levels, which has no slope).
- H3a-role / H3a-label: two-sided paired test on the item-level difference averaged over the other factor,
  d_i = (user/self + user/other - assistant/self - assistant/other) / 2 for role, (other - self) likewise for label
  (design §3.5; analysis/power.py compared single cells). The pilot distribution of d_i over {-1, -1/2, 0, 1/2, 1}
  is rescaled in its non-zero mass (discordance x {0.5, 1, 1.5}) and exponentially tilted to the target mean
  (delta/2, delta, half the pilot estimate). D-inj test n.
- H2b: intersection-union test on the top probe quintile of initially wrong test items: (i) non-inferiority, the
  upper one-sided bound of W->R(F2) - W->R(F0) < delta_w, and (ii) W->R(F3(1.0)) - W->R(F0) > 0. Outcome triples of
  the dev wrong items are resampled (the quintile selection is not modelled, so the pattern is that of all wrong
  items); n = a fifth of the test wrong count. delta_w is not fixed yet: 5 and 10 pp.
Level: alpha / 6 (first Holm step). Usage: python analysis/p2_power_more.py
"""
import json
import math
from pathlib import Path

import numpy as np

from stats import gee_slope, one_sided_paired

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "reports" / "02_power_more_tables.md"
ALPHA, FAMILY, DELTA, SEED = 0.05, 6, 0.03, 0
SIMS, SIMS_GEE = 2000, 400
N_DNAT, N_DINJ = 1455, 1635
TEST_WRONG = {"4B": "p1-initial-4B-d2ebdea", "1.7B": "p1-initial-1.7B-d2ebdea"}


def jl(p):
    return [json.loads(l) for l in open(p, encoding="utf-8")]


def tilt(values, probs, target):
    """Exponential tilting of a discrete distribution to the target mean (bisection on theta)."""
    lo, hi = -50.0, 50.0
    for _ in range(100):
        th = (lo + hi) / 2
        w = probs * np.exp(th * values)
        w /= w.sum()
        lo, hi = (th, hi) if (w * values).sum() < target else (lo, th)
    return w


def h3a_power(d, n, rng):
    values = np.array([-1, -0.5, 0, 0.5, 1])
    base = np.array([(np.isclose(d, v)).mean() for v in values])
    pilot = float(d.mean())
    rows = []
    for dm in (0.5, 1.0, 1.5):
        nz = 1 - base[2]
        p = base.copy()
        scale = min(dm, 1 / nz) if nz > 0 else 0
        p[[0, 1, 3, 4]] *= scale
        p[2] = 1 - p[[0, 1, 3, 4]].sum()
        for name, eff in (("δ/2", DELTA / 2), ("δ", DELTA), ("half pilot", abs(pilot) / 2)):
            reach = (p * np.abs(values)).sum()
            if eff >= reach:
                rows.append({"disc": float(1 - p[2]), "effect": eff, "scenario": name, "power": None})
                continue
            w = tilt(values, p, eff)
            hits = 0
            for _ in range(SIMS):
                x = rng.choice(values, n, p=w)
                se = x.std(ddof=1) / math.sqrt(n)
                z = x.mean() / se if se > 0 else 0
                hits += math.erfc(abs(z) / math.sqrt(2)) < ALPHA / FAMILY
            rows.append({"disc": float(1 - p[2]), "effect": eff, "scenario": name, "power": hits / SIMS})
    return pilot, rows


def main():
    rng = np.random.default_rng(SEED)
    out = {}
    lines = ["# Power for H1b, H3a (pre-registered estimands) and H2b (generated by analysis/p2_power_more.py; dev pilots)", "",
             f"Level α/{FAMILY} (first Holm step); δ = {100 * DELTA:.0f} pp. 'none' = the scenario effect exceeds what the "
             "scaled discordance allows. See the script docstring for each scenario.", ""]
    for model in ("4B", "1.7B"):
        pairs = json.loads((ROOT / "analysis" / "out" / f"p2_pairs_{model}.json").read_text())
        res = {}
        lines += [f"## Qwen3-{model}", ""]

        # H1b
        items = [it["outcomes"] for it in pairs["H1b_F3"]["items"]]
        Y = np.array(items, float)
        levels = np.array([0.5, 0.7, 0.9, 1.0])
        h1b = {}
        for name, mix in (("pilot slope", 0.0), ("half slope", 0.5)):
            hits = 0
            for _ in range(SIMS_GEE):
                idx = rng.integers(0, len(Y), N_DNAT)
                y = Y[idx].copy()
                shuf = rng.random(N_DNAT) < mix
                for i in np.where(shuf)[0]:
                    rng.shuffle(y[i])
                hits += gee_slope(y.ravel(), np.tile(levels, N_DNAT), np.repeat(np.arange(N_DNAT), 4)) < ALPHA / FAMILY
            h1b[name] = hits / SIMS_GEE
        acc = Y.mean(0)
        res["H1b"] = {"pilot_acc_by_p": acc.tolist(), "power": h1b}
        lines += [f"**H1b** (n = {N_DNAT}, {SIMS_GEE} simulations; dev accuracy at p = 0.5/0.7/0.9/1.0: "
                  f"{' / '.join(f'{100 * a:.1f}' for a in acc)} %): power {h1b['pilot slope']:.2f} at the pilot slope, "
                  f"{h1b['half slope']:.2f} at half of it.", ""]

        # H3a-role, H3a-label
        C = np.array([it["outcomes"] for it in pairs["H3a_dinj_F0"]["items"]], float)   # a/s, a/o, u/s, u/o
        assert pairs["H3a_dinj_F0"]["conditions"] == ["assistant/self/F0", "assistant/other/F0", "user/self/F0", "user/other/F0"]
        lines += ["| Hypothesis | Pilot estimate (pp) | Scenario discordance % | Scenario | Effect (pp) | Power |", "|---|---|---|---|---|---|"]
        for hname, d in (("H3a-role", (C[:, 2] + C[:, 3] - C[:, 0] - C[:, 1]) / 2),
                         ("H3a-label", (C[:, 1] + C[:, 3] - C[:, 0] - C[:, 2]) / 2)):
            pilot, rows = h3a_power(d, N_DINJ, rng)
            res[hname] = {"pilot": pilot, "rows": rows}
            for r in rows:
                lines.append(f"| {hname} | {100 * pilot:.1f} | {100 * r['disc']:.1f} | {r['scenario']} | {100 * r['effect']:.1f} | "
                             f"{'none' if r['power'] is None else f'{r['power']:.2f}'} |")
        lines.append("")

        # H2b
        T = np.array([it["outcomes"] for it in pairs["H2b_F0_F2_F3"]["items"] if not it["correct0"]], float)   # F0, F2, F3
        init = jl(ROOT / "results" / "p1" / model / TEST_WRONG[model] / "initial.jsonl")
        n_wrong = sum(r["split"] == "test" and not r["correct"] for r in init)
        h2b = {}
        for k in (1.0, 2.0):
            n = int(round(k * n_wrong / 5))
            for dw in (0.05, 0.10):
                hits = 0
                for _ in range(SIMS):
                    s = T[rng.integers(0, len(T), n)]
                    p_i = one_sided_paired(s[:, 1], s[:, 0], dw, "less")
                    p_ii = one_sided_paired(s[:, 2], s[:, 0], 0.0, "greater")
                    hits += max(p_i, p_ii) < ALPHA / FAMILY
                h2b[f"pool ×{k:g}, δ_w {100 * dw:.0f} pp"] = {"n": n, "power": hits / SIMS}
        res["H2b"] = {"dev_wrong": len(T), "dev_wr_rates": T.mean(0).tolist(), "power": h2b}
        lines += [f"**H2b** (dev wrong items {len(T)}; their W→R under F0 / F2 / F3(1.0): "
                  f"{' / '.join(f'{100 * a:.1f}' for a in T.mean(0))} %): " +
                  "; ".join(f"{k}: n = {v['n']}, power {v['power']:.2f}" for k, v in h2b.items()) + ".", ""]
        out[model] = res
    (ROOT / "analysis" / "out" / "power_more.json").write_text(json.dumps(out, indent=1))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(OUT.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
