"""Compare the run host's full file listing (results/archive/vm/<id>/results_listing.tsv, written by
cloud/archive_sequence.sh) with the control host, and summarize what has no local copy by kind:
- listed as remote-only in a synced run's manifest (activations; known, hash-checked);
- extra files inside synced runs that the manifest does not list (intermediate shards, adapters, per-checkpoint files);
- runs never synced (no local directory): smoke, dev or superseded runs, by status in runs.jsonl;
- other files outside run directories.
Appends the summary to reports/09_completeness.md.
Usage: python analysis/p8_vm_diff.py
"""
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    lst = sorted((ROOT / "results" / "archive" / "vm").glob("*/results_listing.tsv"))[-1]
    rows = [l.split("\t") for l in lst.read_text(encoding="utf-8").splitlines() if l.strip()]
    status = {}
    for l in open(ROOT / "runs.jsonl", encoding="utf-8"):
        if l.strip():
            r = json.loads(l)
            status[r.get("id") or r.get("run_id")] = r.get("status")
    local_runs = {str(p.parent.relative_to(ROOT / "results")).replace("\\", "/") for p in (ROOT / "results").rglob("manifest.json")}
    kinds = defaultdict(lambda: {"files": 0, "bytes": 0, "dirs": set()})
    ext = defaultdict(lambda: [0, 0])
    total = 0
    for path, size, _ in rows:
        if path.startswith("archive/"):
            continue
        total += 1
        if (ROOT / "results" / path).exists():
            continue
        size = int(size)
        parts = path.split("/")
        run = next(("/".join(parts[:k]) for k in range(len(parts) - 1, 0, -1) if "/".join(parts[:k]) in local_runs), None)
        if run:
            ro = ROOT / "results" / run / "remote_only.json"
            names = {e["name"] for e in json.loads(ro.read_text(encoding="utf-8"))} if ro.exists() else set()
            kind = "remote-only (listed in the run's manifest)" if "/".join(parts[len(run.split("/")):]) in names else "extra files in synced runs (not in their manifests)"
            key = run
        elif len(parts) >= 4:
            rid = parts[2]
            st = status.get(rid, "not in runs.jsonl")
            kind = f"runs never synced (runs.jsonl status: {st})"
            key = "/".join(parts[:3])
        else:
            kind, key = "other files outside run directories", path
        k = kinds[kind]
        k["files"] += 1
        k["bytes"] += size
        k["dirs"].add(key)
        e = Path(path).suffix or "(none)"
        ext[e][0] += 1
        ext[e][1] += size
    L = ["", "## Run host against control host (generated by analysis/p8_vm_diff.py)", "",
         f"Source: `{str(lst.relative_to(ROOT)).replace(chr(92), '/')}`: every file under `/home/results` on the run host, "
         f"listed by `cloud/archive_sequence.sh` ({total} files). Files without a local copy, by kind:", "",
         "| Kind | Files | Directories | Size |", "|---|---|---|---|"]
    for kind, k in sorted(kinds.items(), key=lambda kv: -kv[1]["bytes"]):
        L.append(f"| {kind} | {k['files']} | {len(k['dirs'])} | {k['bytes'] / 1e9:.2f} GB |")
    L += ["", "By file type:", "", "| Extension | Files | Size |", "|---|---|---|"]
    L += [f"| {e} | {n} | {b / 1e9:.2f} GB |" for e, (n, b) in sorted(ext.items(), key=lambda kv: -kv[1][1])[:12]]
    L += ["", "Directories per kind:", ""]
    for kind, k in sorted(kinds.items(), key=lambda kv: -kv[1]["bytes"]):
        ds = sorted(k["dirs"])
        L.append(f"- **{kind}** ({len(ds)}): " + ", ".join(f"`{d}`" for d in ds[:40]) + (" …" if len(ds) > 40 else ""))
    rep = ROOT / "reports" / "09_completeness.md"
    rep.write_text(rep.read_text(encoding="utf-8").split("\n## Run host against control host")[0].rstrip("\n") + "\n" + "\n".join(L) + "\n",
                   encoding="utf-8", newline="\n")
    print("\n".join(L[:30]))


if __name__ == "__main__":
    main()
