"""Readout diagnostic on math dev (second review, item C; DEVIATIONS D18). Exploratory, dev only.

For each model (4B, 8B, T8B) and readout variant (src/score/verbal_variants.py: W0 the fixed question, W1 third
person, W2 one-word reply, W3 reversed polarity, W4 true/false): pooled dev AUROC of s for a0 correctness and per
dataset; the median and minimum probability mass on the candidates; the mean normalized "correct" probability on
right and on wrong answers; calibration of that probability (Brier score and 10-bin expected calibration error). The
dev-selected variant is the one the fixed rule picks (verbal_variants.select); W0 stays primary.
Input: the fu-dev verbal-variants run directories (synced under results/v2/fu-dev/<model>/).
-> reports/fu_07_verbal_variants.md, analysis/out/fu_07_verbal_variants.json
Usage: python analysis/fu_verbal_variants.py --runs <dir> [<dir> ...]
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np
from sklearn.metrics import roc_auc_score

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.score.verbal_variants import MIN_MASS, SELECT_MARGIN, VARIANTS, select  # noqa: E402


def ece(p, y, bins=10):
    idx = np.minimum((p * bins).astype(int), bins - 1)
    return float(sum(abs(p[idx == b].mean() - y[idx == b].mean()) * (idx == b).mean() for b in range(bins) if (idx == b).any()))


def summarize(run):
    rows = [json.loads(line) for line in open(Path(run) / "variants.jsonl", encoding="utf-8")]
    y = np.array([r["correct"] for r in rows], int)
    ds = np.array([r["dataset"] for r in rows])
    out = {"n": len(rows), "a0 accuracy": float(y.mean()), "variants": {}}
    for v in VARIANTS:
        s = np.clip(np.array([r[v]["s"] if r[v]["s"] is not None else (np.inf if r[v]["p_neg"] == 0 else -np.inf)
                              for r in rows], float), -1e6, 1e6)
        mass = np.array([r[v]["mass"] for r in rows])
        pn = np.array([r[v]["p_pos"] / r[v]["mass"] if r[v]["mass"] > 0 else 0.5 for r in rows])
        au = lambda m: float(roc_auc_score(y[m], s[m])) if 0 < y[m].sum() < m.sum() else None  # noqa: E731
        out["variants"][v] = {"query": VARIANTS[v][0], "auroc": au(np.ones(len(y), bool)),
                              "auroc by dataset": {d: au(ds == d) for d in sorted(set(ds))},
                              "median mass": float(np.median(mass)), "min mass": float(mass.min()),
                              "mean p(correct) | right": float(pn[y == 1].mean()), "mean p(correct) | wrong": float(pn[y == 0].mean()),
                              "brier": float(((pn - y) ** 2).mean()), "ece": ece(pn, y)}
    chosen, _ = select(run)
    out["dev-selected variant"] = chosen
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", nargs="+", required=True)
    a = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")
    res = {}
    for r in a.runs:
        model = json.loads((Path(r) / "config.json").read_text(encoding="utf-8"))["model"] if (Path(r) / "config.json").exists() \
            else Path(r).parent.name
        res[model] = summarize(r)
    (ROOT / "analysis" / "out" / "fu_07_verbal_variants.json").write_text(json.dumps(res, indent=1), encoding="utf-8", newline="\n")
    L = ["# Readout variants on math dev (generated by analysis/fu_verbal_variants.py)", "",
         f"**Exploratory, dev only** (DEVIATIONS D18). Selection rule (src/score/verbal_variants.py, fixed before any output): "
         f"eligible if median mass ≥ {MIN_MASS}; the best eligible W1–W4 is selected if its pooled AUROC exceeds W0's by "
         f"≥ {SELECT_MARGIN}. W0 stays primary.", ""]
    for m, o in res.items():
        L += [f"## {m} (dev n {o['n']}, a0 accuracy {100 * o['a0 accuracy']:.1f} %; dev-selected variant: {o['dev-selected variant'] or 'none'})", "",
              "| Variant | Query | AUROC | By dataset | Median mass | Min mass | p(correct) right / wrong | Brier | ECE |",
              "|---|---|---|---|---|---|---|---|---|"]
        for v, s in o["variants"].items():
            bd = ", ".join(f"{d} {x:.3f}" if x is not None else f"{d} —" for d, x in s["auroc by dataset"].items())
            au = "—" if s["auroc"] is None else f"{s['auroc']:.3f}"
            L.append(f"| {v} | {s['query']} | {au} | {bd} | {s['median mass']:.3f} | {s['min mass']:.3f} | "
                     f"{s['mean p(correct) | right']:.3f} / {s['mean p(correct) | wrong']:.3f} | {s['brier']:.3f} | {s['ece']:.3f} |")
        L.append("")
    (ROOT / "reports" / "fu_07_verbal_variants.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
