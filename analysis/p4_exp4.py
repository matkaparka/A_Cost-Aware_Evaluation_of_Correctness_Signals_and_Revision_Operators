"""Exp 4 estimates (exploratory; design Exp 4, prereg §3.3): estimates and 95 % cluster-bootstrap CIs only, no Holm and
no outcome category (prereg §8). Rules fixed in src/patch/select.py before any Exp 4 output existed.
-> reports/04_<out>.md and analysis/out/<out>.json

- Unit: the canonical problem (D-inj); bootstrap `src.patch.select.mean_ci` (the scheme of analysis/p6_confirmatory.Boot,
  10,000 resamples, seed 0).
- Effects are in metric units: lp_gold in nats, marker in logits (logit(Let) - logit(The)). A component's effect is
  m(receiver patched with the donor at that component) - m(receiver); the total effect is m(donor) - m(receiver);
  receiver = (assistant, self), donor = (user, other), F0.
- Dev: total effect; mean attribution per (layer, group), the marker's non-selectable final block marked *; the
  top-20 real-patching table with the k rule's flags; the frozen components.
- Test: per frozen component of each metric, the test mean effect, CI and "replicated" (`select.confirm`: the dev sign
  and a CI excluding 0); the test total effect; the share of the total effect (mean effect / mean total, descriptive);
  the self-patch invariant; sample status (planned 200, min_n 100: complete / pre-registered partial / descriptive).
Usage: python analysis/p4_exp4.py --dev results/p2/4B/<dev run> [--test results/main/4B/<test run>] --out p4_4B_exp4
       (--out-root DIR: smoke checks only)
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.patch import select as S  # noqa: E402
from src.patch.core import GROUPS, METRICS  # noqa: E402

PLANNED, MIN_N = 200, 100   # analysis/p3_min_n.py, configs/blocks.yaml 4B-exp4


def jl(p):
    return [json.loads(l) for l in open(p, encoding="utf-8")]


def effects(rows, arms):
    """rows -> (item ids, clusters, {metric: [items, len(arms)] effects vs base_r}, {metric: total effect [items]})."""
    by = {}
    for r in rows:
        by.setdefault(r["item_id"], {})[r["arm"]] = r
    ids = sorted(by)
    cl = [by[i]["base_r"]["canonical_id"] for i in ids]
    eff = {m: np.array([[by[i][a][m] - by[i]["base_r"][m] for a in arms] for i in ids]) for m in METRICS}
    tot = {m: np.array([by[i]["base_d"][m] - by[i]["base_r"][m] for i in ids]) for m in METRICS}
    err = {m: max(abs(by[i]["self_patch"][m] - by[i]["base_r"][m]) for i in ids) for m in METRICS}
    return ids, cl, eff, tot, err


def f(x, d=3):
    return "–" if x is None else f"{x:+.{d}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dev", required=True)
    ap.add_argument("--test", default=None)
    ap.add_argument("--out", required=True)
    ap.add_argument("--n-boot", type=int, default=S.N_BOOT)
    ap.add_argument("--out-root", default=str(ROOT), help="smoke checks only: write reports/ and analysis/out/ here")
    args = ap.parse_args()
    root = Path(args.out_root)
    dev = ROOT / args.dev
    fz = json.loads((dev / "frozen.json").read_text(encoding="utf-8"))
    out = {"dev_run": fz["dev_run_id"], "frozen_k": {m: fz["selection"][m]["k"] for m in METRICS}}
    lines = [f"# Exp 4 activation patching, {fz['model']} (generated by analysis/p4_exp4.py; exploratory)", "",
             f"Receiver {tuple(fz['receiver'])}, donor {tuple(fz['donor'])}, F0, D-inj. Effects: m(receiver patched "
             "with the donor) − m(receiver); lp_gold in nats, marker in logits. 95 % cluster-bootstrap CIs "
             "(canonical problems).", "", f"## Dev ({fz['dev_run_id']}, {fz['n_dev_pairs']} pairs)", ""]

    union = sorted({(s["layer"], s["group"]) for m in METRICS for s in fz["selection"][m]["real"]},
                   key=lambda c: (c[0], GROUPS.index(c[1])))
    ids, cl, eff, tot, err = effects(jl(dev / "patch_rows.jsonl"), [f"L{L}:{g}" for L, g in union])
    tm, tl, th = S.mean_ci(np.stack([tot[m] for m in METRICS], 1), cl, args.n_boot)
    out["dev_total"] = {m: [float(tm[k]), float(tl[k]), float(th[k])] for k, m in enumerate(METRICS)}
    out["dev_self_patch_max_abs_err"] = err
    lines += ["| Metric | Total effect (donor − receiver) | 95 % CI | k |", "|---|---|---|---|"]
    lines += [f"| {m} | {f(tm[k])} | [{f(tl[k])}, {f(th[k])}] | {fz['selection'][m]['k']} |" for k, m in enumerate(METRICS)]
    A = np.load(dev / "attr.npz")["attr"]
    for k, m in enumerate(METRICS):
        mu = A[:, k].mean(0)
        excl = fz["rule"]["not_selectable"][m]
        lines += ["", f"### Mean attribution, {m} (layer × group)", ""]
        if excl:
            lines += [f"Layers marked * are not selectable for {m} (frozen rule: {fz['rule']['not_selectable_reason']}).", ""]
        lines += ["| Layer | " + " | ".join(GROUPS) + " |", "|---|" + "---|" * len(GROUPS)]
        lines += [f"| {L}{'*' if L in excl else ''} | " + " | ".join(f(v, 2) for v in mu[L]) + " |" for L in range(mu.shape[0])]
        lines += ["", f"### Real patching of the attribution top {S.N_REAL}, {m}", "",
                  "| Attr. rank | Layer | Group | Mean attr. | Mean effect | 95 % CI | Eligible | Frozen |", "|---|---|---|---|---|---|---|---|"]
        frozen = {(c["layer"], c["group"]) for c in fz["selection"][m]["frozen"]}
        for s, a in zip(fz["selection"][m]["real"], fz["selection"][m]["attr_top"]):
            lines.append(f"| {s['attr_rank'] + 1} | {s['layer']} | {s['group']} | {f(a['mean_attr'])} | {f(s['mean'])} | "
                         f"[{f(s['lo'])}, {f(s['hi'])}] | {'yes' if s['eligible'] else 'no'} | "
                         f"{'yes' if (s['layer'], s['group']) in frozen else ''} |")
    out["dev_selection"] = fz["selection"]

    if args.test:
        test = ROOT / args.test
        comps = [(c["layer"], c["group"]) for c in fz["test_components"]]
        ids, cl, eff, tot, err = effects(jl(test / "rows.jsonl"), [f"L{L}:{g}" for L, g in comps])
        n = len(ids)
        status = "complete" if n >= PLANNED else ("pre-registered partial sample" if n >= MIN_N else "descriptive only")
        tm, tl, th = S.mean_ci(np.stack([tot[m] for m in METRICS], 1), cl, args.n_boot)
        out["test"] = {"run": test.name, "n": n, "status": status, "self_patch_max_abs_err": err,
                       "total": {m: [float(tm[k]), float(tl[k]), float(th[k])] for k, m in enumerate(METRICS)}, "confirm": {}}
        lines += ["", f"## Test ({test.name}, {n} pairs; {status})", "",
                  f"Self-patch max |error|: " + ", ".join(f"{m} {err[m]:.2e}" for m in METRICS), "",
                  "| Metric | Total effect | 95 % CI |", "|---|---|---|"]
        lines += [f"| {m} | {f(tm[k])} | [{f(tl[k])}, {f(th[k])}] |" for k, m in enumerate(METRICS)]
        for k, m in enumerate(METRICS):
            fr = [(c["layer"], c["group"], c["dev_mean"]) for c in fz["selection"][m]["frozen"]]
            e = eff[m][:, [comps.index((L, g)) for L, g, _ in fr]]
            res = S.confirm(e, cl, fr, args.n_boot)
            for r in res:
                r["share_of_total"] = r["test_mean"] / tm[k] if tm[k] else None
            out["test"]["confirm"][m] = res
            lines += ["", f"### Frozen components, {m}", "",
                      "| Layer | Group | Dev mean | Test mean | 95 % CI | Share of total | Replicated |", "|---|---|---|---|---|---|---|"]
            lines += [f"| {r['layer']} | {r['group']} | {f(r['dev_mean'])} | {f(r['test_mean'])} | [{f(r['lo'])}, {f(r['hi'])}] | "
                      f"{f(r['share_of_total'], 2)} | {'yes' if r['replicated'] else 'no'} |" for r in res]
    for sub in ("analysis/out", "reports"):
        (root / sub).mkdir(parents=True, exist_ok=True)
    (root / "analysis" / "out" / f"{args.out}.json").write_text(json.dumps(out, indent=1, default=float))
    (root / "reports" / f"04_{args.out.removeprefix('p4_')}.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote reports/04_{args.out.removeprefix('p4_')}.md, analysis/out/{args.out}.json")


if __name__ == "__main__":
    main()
