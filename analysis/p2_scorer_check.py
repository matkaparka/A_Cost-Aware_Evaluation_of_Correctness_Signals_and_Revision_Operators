"""Scorer-version impact check (CLAUDE.md rule 8; P2 hand checks): rescore stored outputs with the current scorer
and count every (status, correct) change against what the run recorded.

1. P1 initial answers (all splits; correctness only, the agent looks at counts) for every model.
2. P2 Exp 1A/1B rows (the runner's own extraction; Tsui rows are rescored in analysis/p2_exp01.py instead).
3. A seeded sample of Tsui-cell rows with the text tail, for the manual check recorded in the P2 report.

Writes reports/02_scorer_check.md. Usage: python analysis/p2_scorer_check.py [--sample-seed N] [--n 12]
"""
import argparse
import json
import random
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.score.scorer import SCORER_VERSION, score  # noqa: E402

OUT = ROOT / "reports" / "02_scorer_check.md"


def jl(p):
    return [json.loads(l) for l in open(p, encoding="utf-8")]


def done_runs(pattern):
    """Done runs without a tag: P3's expansion runs (-ext-, scored by 1.1.0 at run time) and tagged dev pilots are
    outside this check of the scorer change on earlier runs."""
    reg = {r["run_id"]: r for r in jl(ROOT / "runs.jsonl")}
    return sorted(p for p in ROOT.glob(pattern) if reg.get(p.name, {}).get("status") == "done"
                  and re.fullmatch(r"p[12]-(initial|exp01-dev)-(1\.7B|4B|8B)-[0-9a-f]{7}", p.name))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sample-seed", type=int, default=1105)
    ap.add_argument("--n", type=int, default=12)
    a = ap.parse_args()
    dnat = {r["item_id"]: r for r in jl(ROOT / "data" / "processed" / "dnat.jsonl")}
    dinj = {r["item_id"]: r for r in jl(ROOT / "data" / "processed" / "dinj.jsonl")}
    lines = [f"# Scorer {SCORER_VERSION} impact check (generated by analysis/p2_scorer_check.py)", "",
             "| Run | Rows | Changed (status or correctness) |", "|---|---|---|"]
    for run in done_runs("results/p1/*/p1-initial-*"):
        rows = jl(run / "initial.jsonl")
        diff = Counter()
        for r in rows:
            s = score(r["a0"], dnat[r["item_id"]]["gold"], finish_reason=r.get("finish_reason"))
            if (s["status"], s["correct"]) != (r["status"], r["correct"]):
                diff[f"{r['status']}/{r['correct']} → {s['status']}/{s['correct']}"] += 1
        lines.append(f"| {run.name} | {len(rows)} | {dict(diff) if diff else 0} |")
    rnd = random.Random(a.sample_seed)
    sample = []
    for run in done_runs("results/p2/*/p2-exp01-dev-*"):
        if "smoke" in run.name:
            continue
        texts = {g["prompt_key"]: g["text"] for g in jl(run / "generations.jsonl")}
        rows = jl(run / "rows.jsonl")
        diff, n = Counter(), 0
        for r in rows:
            if r["exp"] not in ("1A", "1B") or r.get("prompt_key") is None:
                continue
            n += 1
            gold = (dnat.get(r["item_id"]) or dinj[r["item_id"]])["gold"]
            s = score(texts[r["prompt_key"]], gold, finish_reason=r["finish_reason"])
            if (s["status"], s["correct"]) != (r["status"], r["correct"]):
                diff[f"{r['cond']}: {r['status']}/{r['correct']} → {s['status']}/{s['correct']}"] += 1
        lines.append(f"| {run.name} (1A/1B) | {n} | {dict(diff) if diff else 0} |")
        tsui = [r for r in rows if r["exp"] == "tsui" and r["finish_reason"] == "stop" and texts[r["prompt_key"]].strip()]
        for r in rnd.sample(tsui, a.n):
            it = dinj[r["item_id"]]
            s = score(texts[r["prompt_key"]], it["gold"], finish_reason="stop", last_number=True)
            tail = " ".join(texts[r["prompt_key"]].split())[-220:].replace("|", "\\|")
            sample.append(f"| {run.name.split('-')[3]} | {r['item_id']} | {r['cond']} | {it['gold']} | "
                          f"{it.get('injected_answer')} | {s['status']} | {s['pred']} | {s['correct']} | {tail} |")
    lines += ["", f"## Tsui-cell sample for the manual check (seed {a.sample_seed}, {a.n} non-empty rows per model)", "",
              "| Model | Item | Cond | Gold | Injected | Status | Pred | Scored correct | Text tail |",
              "|---|---|---|---|---|---|---|---|---|", *sample, ""]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
