"""Persistent streams (H4c; exploratory, descriptive; DEVIATIONS D10): tables from the run's own summaries.
The trajectory is the unit (3 order seeds per condition); no CI, no test (prereg §1, §3.3).
- Evaluation: eval_summary.json (definitions in src/ttt/streams.py summarize()), per condition and checkpoint: the mean
  over the 3 seeds and the range [min, max].
- Stream steps: steps.jsonl, per trajectory: a0 accuracy and status over the 200 steps, the verdict used, updates
  applied and the anomalies of update.update.
- POST HOC (DEVIATIONS D12, written after reading the evaluation at k = 25 and 50, where self collapsed): the collapse
  onset, the first step of a run of RUN consecutive truncated a0 (single truncations happen on hard items in every
  condition); for the trained conditions, the updates applied before it, split by the loss the verdict selected (NLL if
  the verdict says correct, unlikelihood otherwise) and by a0's true correctness; mean a0 length by 25-step bin.
-> reports/04_<out>.md and analysis/out/<out>.json
Usage: python analysis/p4_streams.py --run results/main/4B/main-streams-test-4B-f15b933 --out p4_4B_streams
"""
import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONDS = ["self", "ext", "random", "context"]
RUN = 10


def jl(p):
    return [json.loads(l) for l in open(p, encoding="utf-8")]


def rng(vals, pct=True):
    f = (lambda v: f"{100 * v:.1f}") if pct else (lambda v: f"{v:.0f}")
    m = sum(vals) / len(vals)
    return f"{f(m)} [{f(min(vals))}, {f(max(vals))}]"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")
    run = Path(a.run)
    summ = json.loads((run / "eval_summary.json").read_text(encoding="utf-8"))
    met = json.loads((run / "metrics.json").read_text(encoding="utf-8"))
    steps = jl(run / "steps.jsonl")
    ks = sorted(summ, key=int)
    trajs = met["trajectories"]
    CONDS = json.loads((run / "config.json").read_text(encoding="utf-8")).get("conditions", globals()["CONDS"])  # D16 controls
    by_cond = {c: [t for t in trajs if t.split("-")[0] == c] for c in CONDS}

    def ev(k, t, key):
        s = summ[k]["base"] if k == "0" else summ[k][t]
        return s[key]

    def trunc(k, t):
        s = summ[k]["base"] if k == "0" else summ[k][t]
        return s["greedy_status"].get("truncated", 0) / s["n"]

    out = {"run": str(run), "eval": {}, "steps": {}, "post_hoc": {}}
    for c in CONDS:
        out["eval"][c] = {k: {key: [ev(k, t, key) for t in by_cond[c]] for key in
                              ("acc_greedy", "acc_samples", "frac_says_correct", "self_verdict_acc", "probe_acc",
                               "agreement", "mean_out_tokens")} | {"truncated": [trunc(k, t) for t in by_cond[c]]}
                          for k in ks}

    st = defaultdict(list)
    for r in steps:
        st[r["traj"]].append(r)
    for t in trajs:
        rs = sorted(st[t], key=lambda r: r["step"])
        upd = [r.get("update") or {} for r in rs]
        out["steps"][t] = {
            "n": len(rs), "a0_acc": sum(r["a0_correct"] for r in rs) / len(rs),
            "a0_status": dict(Counter(r["a0_status"] for r in rs)),
            "says_correct": sum(bool(r["says_correct"]) for r in rs) / len(rs),
            "self_verdict_acc": sum(bool(r["says_correct"]) == bool(r["a0_correct"]) for r in rs) / len(rs),
            "applied": sum(bool(u.get("applied")) for u in upd),
            "anomalies": dict(Counter(u["anomaly"] for u in upd if u.get("anomaly"))),
            "final_total_norm": met["final_total_norm"].get(t)}
        tr = [r["a0_status"] == "truncated" for r in rs]
        onset = next((rs[i]["step"] for i in range(len(rs) - RUN + 1) if all(tr[i:i + RUN])), None)
        pre = [r for r in rs if onset is None or r["step"] < onset]
        cells = Counter()
        if t.split("-")[0] in ("self", "ext", "nll", "matched"):
            for r in pre:
                if (r.get("update") or {}).get("applied"):
                    cells[("NLL" if r["verdict"] else "UL", "a0 right" if r["a0_correct"] else "a0 wrong")] += 1
        bins = defaultdict(list)
        for r in rs:
            bins[r["step"] // 25].append(r["a0_tokens"])
        out["post_hoc"][t] = {"onset_step": onset,
                              "updates_before": {f"{l}, {w}": n for (l, w), n in sorted(cells.items())},
                              "mean_a0_tokens_by_bin": [round(sum(v) / len(v)) for _, v in sorted(bins.items())]}
    (ROOT / "analysis" / "out" / f"{a.out}.json").write_text(json.dumps(out, indent=1))

    L = ["# Persistent streams, 4B test (generated by analysis/p4_streams.py)", "",
         f"Run `{run.as_posix()}`: {len(trajs)} trajectories ({len(CONDS)} conditions × {len(trajs) // len(CONDS)} order seeds) × {met['steps']} steps; "
         f"evaluation on {summ['0']['base']['n']} dev items at k = {', '.join(ks)}. **Exploratory, descriptive (H4c; "
         "DEVIATIONS D10)**: the trajectory is the unit; cells give the mean over the 3 seeds and [min, max]. "
         "k = 0 is the shared base.", "",
         f"Invariants (metrics.json): step-0 a0 identical {met['zero_step_a0_identical']}, step-0 verbal identical "
         f"{met['zero_step_verbal_identical']}, realized increment norm max relative error "
         f"{met['realized_increment_norm_max_rel_err']:.1e}.", "",
         "## Evaluation: greedy accuracy (%) by checkpoint", "",
         "| Condition | " + " | ".join(f"k={k}" for k in ks) + " |", "|---|" + "---|" * len(ks)]
    for c in CONDS:
        L.append(f"| {c} | " + " | ".join(rng(out["eval"][c][k]["acc_greedy"]) for k in ks) + " |")
    L += ["", "## Evaluation: greedy outputs truncated at the token cap (%) by checkpoint", "",
          "| Condition | " + " | ".join(f"k={k}" for k in ks) + " |", "|---|" + "---|" * len(ks)]
    for c in CONDS:
        L.append(f"| {c} | " + " | ".join(rng(out["eval"][c][k]["truncated"]) for k in ks) + " |")
    kf = ks[-1]
    L += ["", f"## Evaluation at k = {kf}, all summaries (%, mean out tokens as a count)", "",
          "| Condition | Acc greedy | Acc samples | Says correct | Self-verdict acc | Probe acc | Probe–verbal agreement "
          "| Mean out tokens |", "|---|---|---|---|---|---|---|---|"]
    for c in ["base"] + CONDS:
        e = out["eval"][CONDS[0]]["0"] if c == "base" else out["eval"][c][kf]
        L.append(f"| {c} | " + " | ".join(rng(e[x]) for x in ("acc_greedy", "acc_samples", "frac_says_correct",
                                                                "self_verdict_acc", "probe_acc", "agreement"))
                 + f" | {rng(e['mean_out_tokens'], pct=False)} |")
    L += ["", "## Stream steps, per trajectory", "",
          "| Trajectory | a0 acc | a0 status | Says correct | Self-verdict acc | Updates applied | Anomalies "
          "| Final total norm |", "|---|---|---|---|---|---|---|---|"]
    for t in trajs:
        s = out["steps"][t]
        L.append(f"| {t} | {100 * s['a0_acc']:.1f} % | {s['a0_status']} | {100 * s['says_correct']:.1f} % | "
                 f"{100 * s['self_verdict_acc']:.1f} % | {s['applied']} | {s['anomalies'] or '–'} | "
                 + (f"{s['final_total_norm']:.2f}" if s["final_total_norm"] is not None else "–") + " |")
    L += ["", f"## Post hoc (DEVIATIONS D12): what preceded the collapse onset (first of {RUN} consecutive truncated a0)", "",
          "Written after reading the k = 25 and 50 evaluations. Loss: NLL if the verdict says correct, unlikelihood (UL) "
          "otherwise (src/ttt/update.py); the self stream's verdict is the self-verdict, the ext stream's is true "
          "correctness. An a0 without an answer span gets no update.", "",
          "| Trajectory | Onset (step) | Updates before it (all steps if none), by loss and a0 correctness "
          "| Mean a0 tokens per 25-step bin |", "|---|---|---|---|"]
    for t in trajs:
        p = out["post_hoc"][t]
        L.append(f"| {t} | {p['onset_step'] if p['onset_step'] is not None else 'none'} | "
                 f"{p['updates_before'] or '–'} | {p['mean_a0_tokens_by_bin']} |")
    (ROOT / "reports" / f"04_{a.out}.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
